class RAGPipeline:
    """
    End-to-end Retrieval-Augmented Generation pipeline for the digital twin.

    Flow: raw documents -> load_and_preprocess() -> SimpleRAGRetriever
          -> top-k retrieval for a query -> generation via the LLM,
          grounded only in the retrieved text.

    Parameters
    ----------
    chunk_strategy : str
        Strategy passed to load_and_preprocess()'s ChunkingSystem.
    max_chunk_size : int
        Max words per chunk.
    top_k : int
        How many chunks to retrieve per query by default.
    model : str
        Groq model string used for generation.

    Example
    -------
    >>> rag = RAGPipeline(model="openai/gpt-oss-120b")
    >>> rag.index(documents, source_label="activity_logs")
    >>> answer = rag.ask("What has Davies been working on?")
    >>> rag.visualize()
    """

    def __init__(self, chunk_strategy: str = "smart", max_chunk_size: int = 100,
                 top_k: int = 3, model: str = "openai/gpt-oss-120b"):
        if top_k <= 0:
            raise ValueError(f"top_k must be positive, got {top_k}.")
        self.chunk_strategy = chunk_strategy
        self.max_chunk_size = max_chunk_size
        self.top_k = top_k
        self.model = model

        self.retriever = SimpleRAGRetriever()
        self.indexed_chunks: List[str] = []   # flattened chunk texts fed to the retriever
        self.index_log: List[Dict[str, Any]] = []
        self.query_log: List[Dict[str, Any]] = []
        logger.info(f"RAGPipeline initialized: strategy={chunk_strategy}, "
                    f"max_chunk_size={max_chunk_size}, top_k={top_k}, model={model}")

    # -----------------------------------------------------------------
    # Indexing (load + preprocess + chunk + register with retriever)
    # -----------------------------------------------------------------
    def index(self, documents: List[Dict[str, str]], source_label: str = "unknown") -> Dict[str, Any]:
        """
        Load, clean, extract, and chunk a batch of documents, then register
        every resulting chunk with the retriever so it becomes searchable.
        """
        run_id = len(self.index_log) + 1
        timestamp = datetime.now().isoformat(timespec="seconds")
        logger.info(f"[index {run_id}] starting | source={source_label} | "
                    f"{len(documents) if isinstance(documents, list) else 'N/A'} docs")

        result = {"run_id": run_id, "source": source_label, "timestamp": timestamp,
                   "chunks_added": 0, "warnings": [], "errors": []}

        try:
            processed = load_and_preprocess(
                documents, chunk_strategy=self.chunk_strategy,
                max_chunk_size=self.max_chunk_size
            )
        except (ValueError, TypeError) as e:
            logger.error(f"[index {run_id}] load_and_preprocess failed: {e}")
            result["errors"].append(str(e))
            self.index_log.append(result)
            return result

        if processed["skipped_count"] > 0:
            warning = f"{processed['skipped_count']} document(s) skipped during preprocessing"
            logger.warning(f"[index {run_id}] {warning}")
            result["warnings"].append(warning)

        new_chunks = []
        for doc in processed["documents"]:
            for chunk in doc["chunks"]:
                new_chunks.append(chunk["text"])
            if not doc["chunks"]:
                # chunking disabled or produced nothing — fall back to whole doc text
                new_chunks.append(doc["text"])

        if not new_chunks:
            warning = "No chunks produced from this batch — nothing indexed."
            logger.warning(f"[index {run_id}] {warning}")
            result["warnings"].append(warning)
            self.index_log.append(result)
            return result

        self.indexed_chunks.extend(new_chunks)
        try:
            self.retriever.add_documents(self.indexed_chunks)
        except ValueError as e:
            logger.error(f"[index {run_id}] retriever indexing failed: {e}")
            result["errors"].append(str(e))
            self.index_log.append(result)
            return result

        result["chunks_added"] = len(new_chunks)
        logger.info(f"[index {run_id}] indexed {len(new_chunks)} chunks "
                    f"(total in index: {len(self.indexed_chunks)})")
        self.index_log.append(result)
        return result

    # -----------------------------------------------------------------
    # Retrieval + Generation
    # -----------------------------------------------------------------
    def ask(self, query: str, top_k: int = None) -> Dict[str, Any]:
        """
        Retrieve the most relevant indexed chunks for `query`, then ask the
        LLM to answer using only that retrieved context.
        """
        run_id = len(self.query_log) + 1
        k = top_k or self.top_k
        result = {"run_id": run_id, "query": query, "retrieved": [], "answer": None,
                  "warnings": [], "errors": []}

        # --- Input validation ---
        if query is None or not isinstance(query, str) or query.strip() == "":
            msg = "query must be a non-empty string"
            logger.error(f"[ask {run_id}] {msg}")
            result["errors"].append(msg)
            self.query_log.append(result)
            return result

        if not self.indexed_chunks:
            msg = "Index is empty. Call index() with documents before ask()."
            logger.error(f"[ask {run_id}] {msg}")
            result["errors"].append(msg)
            self.query_log.append(result)
            return result

        # --- Retrieval ---
        try:
            retrieved = self.retriever.process(query, top_n=k)
        except Exception as e:
            logger.error(f"[ask {run_id}] retrieval failed: {e}")
            result["errors"].append(f"retrieval failed: {e}")
            self.query_log.append(result)
            return result

        retrieved = [(doc, score) for doc, score in retrieved if doc is not None]
        if not retrieved:
            warning = "No relevant chunks found for this query (no vocabulary overlap)."
            logger.warning(f"[ask {run_id}] {warning}")
            result["warnings"].append(warning)

        result["retrieved"] = [{"text": doc, "score": round(score, 3)} for doc, score in retrieved]
        logger.info(f"[ask {run_id}] retrieved {len(retrieved)} chunks for query: '{query[:50]}'")

        # --- Generation, grounded strictly in retrieved context ---
        context_block = "\n\n".join(f"[{i+1}] {doc}" for i, (doc, _) in enumerate(retrieved))
        rag_prompt = f"""
You are the digital twin's retrieval-augmented assistant.
Answer the question using ONLY the context below. If the context does not
contain enough information, say so explicitly rather than guessing.

CONTEXT:
{context_block if context_block else "(no relevant context found)"}

QUESTION:
{query}
"""
        try:
            response = client.chat.completions.create(
                model=self.model,
                messages=[{"role": "user", "content": rag_prompt}],
            )
            result["answer"] = response.choices[0].message.content
            logger.info(f"[ask {run_id}] generation complete")
        except Exception as e:
            logger.error(f"[ask {run_id}] generation failed: {e}")
            result["errors"].append(f"generation failed: {e}")

        self.query_log.append(result)
        return result

    # -----------------------------------------------------------------
    # Visualization
    # -----------------------------------------------------------------
    def visualize(self) -> None:
        """
        Plot (1) chunks indexed per index() call, and (2) retrieval scores
        for the most recent ask() call.
        """
        if not self.index_log and not self.query_log:
            logger.warning("Nothing indexed or queried yet — nothing to visualize.")
            return

        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

        # Left: chunks added per index() call
        if self.index_log:
            runs = [r["run_id"] for r in self.index_log]
            added = [r["chunks_added"] for r in self.index_log]
            colors = ["seagreen" if not r["errors"] else "indianred" for r in self.index_log]
            ax1.bar(runs, added, color=colors)
            ax1.set_title("Chunks indexed per run")
            ax1.set_xlabel("Index run")
            ax1.set_ylabel("Chunks added")
            ax1.set_xticks(runs)

        # Right: retrieval scores for the most recent ask()
        if self.query_log:
            last = self.query_log[-1]
            labels = [f"chunk {i+1}" for i in range(len(last["retrieved"]))]
            scores = [c["score"] for c in last["retrieved"]]
            if scores:
                ax2.barh(labels, scores, color="steelblue")
                ax2.set_xlim(0, 1)
                ax2.set_title(f"Retrieval scores: '{last['query'][:30]}...'")
                ax2.set_xlabel("Cosine similarity")
            else:
                ax2.text(0.5, 0.5, "No chunks retrieved", ha="center", va="center")
                ax2.set_title("Retrieval scores")

        plt.tight_layout()
        plt.show()

    # -----------------------------------------------------------------
    # Summary / debugging
    # -----------------------------------------------------------------
    def summary(self) -> None:
        """Print a summary of every index() and ask() call so far."""
        print(f"Indexed chunks total: {len(self.indexed_chunks)}")
        for r in self.index_log:
            print(f"  index run {r['run_id']} | {r['source']} | +{r['chunks_added']} chunks | "
                  f"warnings={len(r['warnings'])} errors={len(r['errors'])}")
        for r in self.query_log:
            print(f"  ask run {r['run_id']} | '{r['query'][:40]}' | "
                  f"retrieved={len(r['retrieved'])} | errors={len(r['errors'])}")
            if r["errors"]:
                print(f"    ⚠️ errors: {r['errors']}")


