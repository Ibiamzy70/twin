# 5. CONTEXT WINDOW MANAGER
# =====================================================================
class ContextWindowManager:
    """
    Tracks a conversation's messages against a model's context window,
    reports a budget breakdown, trims history when it doesn't fit, ingests
    long documents as right-sized chunks, and builds a ready-to-send
    messages list for client.chat(messages) or client.chat.completions.create.

    Parameters
    ----------
    model : str, optional preset name from MODEL_CONTEXT_WINDOWS.
    context_window : explicit override; required if model is not a known preset.
    reserved_output : tokens set aside for the model's reply (never used for input).
    safety_margin : fraction (0-1) of the window kept free as a buffer, on top
        of reserved_output, to absorb estimation error since these are estimates.
    chars_per_token, words_per_token : passed through to TokenEstimator.
    summarizer : optional callable(str) -> str. If given, "summarize" trims
        call it on dropped content instead of discarding it outright. Never
        calls any API on its own -- the caller supplies the function.
    """

    WARN_THRESHOLD, CRIT_THRESHOLD = 75.0, 90.0

    def __init__(self, model: Optional[str] = DEFAULT_MODEL, context_window: Optional[int] = None,
                 reserved_output: int = 1024, safety_margin: float = 0.05,
                 chars_per_token: float = DEFAULT_CHARS_PER_TOKEN, words_per_token: float = 0.75,
                 summarizer: Optional[Callable[[str], str]] = None):
        if context_window is None:
            if model is None or model not in MODEL_CONTEXT_WINDOWS:
                raise ValueError(
                    f"Unknown model '{model}'. Pass context_window explicitly, or use one of: "
                    f"{sorted(MODEL_CONTEXT_WINDOWS)}")
            context_window = MODEL_CONTEXT_WINDOWS[model]
        if context_window <= 0:
            raise ValueError(f"context_window must be positive, got {context_window}.")
        if reserved_output < 0:
            raise ValueError(f"reserved_output cannot be negative, got {reserved_output}.")
        if reserved_output >= context_window:
            raise ValueError("reserved_output must be smaller than context_window.")
        if not (0 <= safety_margin < 1):
            raise ValueError(f"safety_margin must be in [0, 1), got {safety_margin}.")
        if summarizer is not None and not callable(summarizer):
            raise TypeError("summarizer must be callable(str) -> str.")

        self.model = model
        self.context_window = context_window
        self.reserved_output = reserved_output
        self.safety_margin = safety_margin
        self.summarizer = summarizer
        self.estimator = TokenEstimator(chars_per_token, words_per_token)
        self.messages: List[Message] = []
        self.run_history: List[dict] = []
        logger.info("ContextWindowManager ready: model=%s window=%d reserved_output=%d",
                    model, context_window, reserved_output)

    # ---- budget math ----------------------------------------------------
    @property
    def safety_tokens(self) -> int:
        return round(self.context_window * self.safety_margin)

    @property
    def available_for_input(self) -> int:
        return max(0, self.context_window - self.reserved_output - self.safety_tokens)

    def _used_tokens(self) -> int:
        return sum(m.tokens for m in self.messages)

    def budget(self) -> dict:
        used = self._used_tokens()
        available = self.available_for_input
        usage_percent = round((used / available) * 100, 2) if available else float("inf")
        return {
            "model": self.model, "context_window": self.context_window,
            "reserved_output": self.reserved_output, "safety_margin_tokens": self.safety_tokens,
            "available_for_input": available, "used_tokens": used,
            "free_tokens": max(0, available - used), "usage_percent": usage_percent,
            "fits": used <= available, "status": _status_for(usage_percent),
            "message_count": len(self.messages),
        }

    # ---- message management ---------------------------------------------
    def add_message(self, role: str, content: str, pinned: bool = False,
                     priority: int = 0, tag: str = "") -> dict:
        """Validates and appends one message. Raises on a bad role, None
        content, or wrong-typed content; an empty/whitespace string is valid
        (zero tokens), matching the Exercise 1/2 empty-input rule."""
        if role not in VALID_ROLES:
            raise ValueError(f"role must be one of {VALID_ROLES}, got '{role}'.")
        est = self.estimator.estimate(content)      # raises ValueError/TypeError as needed
        msg = Message(role=role, content=content, pinned=pinned, priority=priority,
                     tag=tag, tokens=est["estimated_tokens"])
        self.messages.append(msg)
        b = self.budget()
        if b["status"] in ("critical", "over"):
            logger.warning("Context usage %s%% after adding a %s message (%s).",
                           b["usage_percent"], role, b["status"])
        return b

    def clear(self, keep_pinned: bool = True):
        self.messages = [m for m in self.messages if m.pinned] if keep_pinned else []

    # ---- trimming ---------------------------------------------------------
    def trim(self, strategy: str = "drop_oldest", target_percent: float = 90.0) -> dict:
        """Drops or summarizes non-pinned messages until usage is at or below
        target_percent of available_for_input, or nothing more can be dropped.
        strategy: 'drop_oldest' | 'drop_lowest_priority' | 'summarize'.
        Returns a dict with what was dropped/summarized and the final budget.
        """
        valid = ("drop_oldest", "drop_lowest_priority", "summarize")
        if strategy not in valid:
            raise ValueError(f"strategy must be one of {valid}, got '{strategy}'.")
        limit = self.available_for_input * target_percent / 100
        dropped, summarized = [], []

        def droppable():
            pool = [m for m in self.messages if not m.pinned]
            if strategy == "drop_lowest_priority":
                return sorted(pool, key=lambda m: (m.priority, m.created_at))
            return sorted(pool, key=lambda m: m.created_at)   # oldest first

        while self._used_tokens() > limit:
            pool = droppable()
            if not pool:
                break
            victim = pool[0]
            if strategy == "summarize" and self.summarizer is not None:
                try:
                    short = self.summarizer(victim.content)
                    est = self.estimator.estimate(short)
                    if est["estimated_tokens"] < victim.tokens:
                        victim.content, victim.tokens = short, est["estimated_tokens"]
                        victim.tag = (victim.tag + " summarized").strip()
                        summarized.append(victim.to_api())
                        if self._used_tokens() <= limit:
                            break
                        continue
                except Exception as e:                          # summarizer is caller-supplied
                    logger.error("summarizer failed on a message, falling back to drop: %s", e)
            self.messages.remove(victim)
            dropped.append(victim.to_api())

        result = {"strategy": strategy, "dropped": dropped, "summarized": summarized,
                  "budget": self.budget()}
        if not result["budget"]["fits"]:
            logger.warning("Still over budget after trim() with strategy='%s' "
                           "(%s messages remain, all pinned or undroppable).",
                           strategy, len(self.messages))
        return result

    # ---- document ingestion (integration point) --------------------------
    def ingest_document(self, text: str, source: str = "document", strategy: str = "smart",
                        max_chunk_size: int = 200, extract_entities: bool = True) -> dict:
        """Chunks a long document with ChunkingSystem and estimates tokens per
        chunk against this manager's budget, so a caller knows up front which
        chunks fit alone and which don't. Optionally runs extract_profile_data
        over the whole document for identifiers/temporal/preference metadata."""
        if text is None:
            raise ValueError("text cannot be None")
        if not isinstance(text, str):
            raise TypeError(f"Expected str, got {type(text).__name__}")
        if text.strip() == "":
            return {"source": source, "chunks": [], "entities": {}, "total_estimated_tokens": 0}

        chunker = ChunkingSystem(strategy=strategy, source=source, max_chunk_size=max_chunk_size,
                                 words_per_chunk=max_chunk_size, overlap=min(20, max_chunk_size - 1))
        raw_chunks = chunker.chunk(text, source=source)
        chunks = []
        for c in raw_chunks:
            est = self.estimator.estimate(c["text"])
            chunks.append({**c, "estimated_tokens": est["estimated_tokens"],
                           "fits_alone": est["estimated_tokens"] <= self.available_for_input})
        total = sum(c["estimated_tokens"] for c in chunks)
        entities = extract_profile_data(text) if extract_entities else {}
        logger.info("Ingested '%s': %d chunks, %d estimated tokens total.", source, len(chunks), total)
        return {"source": source, "strategy": strategy, "chunks": chunks,
                "entities": entities, "total_estimated_tokens": total,
                "fits_in_budget": total <= self.available_for_input}

    # ---- integration: build a ready-to-send messages list -----------------
    def build_messages(self, system_prompt: Optional[str] = None, trim_strategy: str = "drop_oldest",
                       target_percent: float = 90.0) -> List[dict]:
        """Pins system_prompt (if given and not already pinned), trims history
        to fit, and returns messages in the shape client.chat(messages) or the
        SDK's client.chat.completions.create(messages=...) expects."""
        if system_prompt is not None and not any(m.pinned and m.role == "system" for m in self.messages):
            self.messages.insert(0, Message(role="system", content=system_prompt, pinned=True,
                                            tokens=self.estimator.estimate(system_prompt)["estimated_tokens"]))
        self.trim(strategy=trim_strategy, target_percent=target_percent)
        return [m.to_api() for m in self.messages]

    @classmethod
    def from_twin_data(cls, user_profile: dict, activity_history: list, temporal_patterns: dict,
                       **kwargs) -> Tuple["ContextWindowManager", str]:
        """Builds a manager plus a system prompt from the project's existing
        user_profile / activity_history / temporal_patterns shape (section 2.2
        of the main changelog), so the twin's system prompt can be sized and
        tracked the same way as everything else."""
        for name, val, typ in (("user_profile", user_profile, dict),
                               ("activity_history", activity_history, list),
                               ("temporal_patterns", temporal_patterns, dict)):
            if not isinstance(val, typ):
                raise TypeError(f"{name} must be a {typ.__name__}, got {type(val).__name__}.")
        system = (f"Role:\nyou are a digital twin for {user_profile.get('name', 'the user')}. "
                 f"you represent their preference and behavioral patterns.\n\n"
                 f"AVAILABLE DATA:\n1. User_profile:\n{user_profile}\n\n"
                 f"2. Activity history:\n{activity_history}\n\n3. Temporal patterns:\n{temporal_patterns}")
        mgr = cls(**kwargs)
        mgr.add_message("system", system, pinned=True, tag="twin-system-prompt")
        return mgr, system

    # ---- reporting ----------------------------------------------------------
    def snapshot(self) -> dict:
        b = self.budget()
        run = {**b, "timestamp": datetime.now().isoformat(timespec="seconds"),
              "estimator_cache": self.estimator.cache_info(),
              "messages": [{"role": m.role, "tokens": m.tokens, "pinned": m.pinned,
                           "priority": m.priority, "tag": m.tag} for m in self.messages]}
        self.run_history.append(run)
        return run

    def summary(self) -> str:
        """Human-readable one-screen status -- the 'user-friendly interface'."""
        b = self.budget()
        bar_len = 30
        filled = min(bar_len, round(bar_len * min(1.0, b["usage_percent"] / 100)))
        bar = "#" * filled + "-" * (bar_len - filled)
        lines = [
            f"Context Window Manager  |  model={self.model}  window={self.context_window:,}",
            f"[{bar}] {b['usage_percent']}%  ({b['status'].upper()})",
            f"used: {b['used_tokens']:,} / available: {b['available_for_input']:,}  "
            f"(reserved for output: {self.reserved_output:,}, safety margin: {self.safety_tokens:,})",
            f"messages: {b['message_count']}  "
            f"(pinned: {sum(m.pinned for m in self.messages)})",
        ]
        if b["status"] != "ok":
            lines.append(f"-> consider calling trim() before the next request.")
        return "\n".join(lines)

    # ---- visualization --------------------------------------------------------
    def visualize(self, title: Optional[str] = None):
        """Two-panel view: (left) tokens per message, colored by role, with the
        available-input line marked; (right) a horizontal gauge of overall
        usage_percent against the 100% limit, capped visually at 150%."""
        b = self.budget()
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 4.5),
                                       gridspec_kw={"width_ratios": [2.2, 1]})

        colors = {"system": "steelblue", "user": "seagreen", "assistant": "darkorange"}
        xs = list(range(1, len(self.messages) + 1))
        heights = [m.tokens for m in self.messages]
        bar_colors = [colors.get(m.role, "gray") for m in self.messages]
        edge = ["black" if m.pinned else "none" for m in self.messages]
        if xs:
            ax1.bar(xs, heights, color=bar_colors, edgecolor=edge, linewidth=1.4)
        ax1.axhline(self.available_for_input, color="red", linestyle="--", linewidth=1,
                    label=f"available ({self.available_for_input:,})")
        ax1.set_title("Tokens per message")
        ax1.set_xlabel("Message position (bold outline = pinned)")
        ax1.set_ylabel("Estimated tokens")
        handles = [plt.Rectangle((0, 0), 1, 1, color=c) for c in colors.values()]
        ax1.legend(handles + [plt.Line2D([0], [0], color="red", linestyle="--")],
                  list(colors.keys()) + ["available limit"], fontsize=8, loc="upper right")

        pct = b["usage_percent"] if b["usage_percent"] != float("inf") else 150
        capped = min(pct, 150)
        color = {"ok": "seagreen", "warning": "goldenrod", "critical": "orangered", "over": "firebrick"}[b["status"]]
        ax2.barh(["usage"], [capped], color=color, height=0.5)
        ax2.axvline(100, color="black", linestyle="--", linewidth=1.2, label="100% limit")
        ax2.axvline(self.WARN_THRESHOLD, color="goldenrod", linestyle=":", linewidth=1)
        ax2.axvline(self.CRIT_THRESHOLD, color="orangered", linestyle=":", linewidth=1)
        ax2.set_xlim(0, 155)
        ax2.set_title(f"Budget usage: {pct:.1f}%\n({b['status'].upper()})")
        ax2.legend(fontsize=8, loc="lower right")

        fig.suptitle(title or f"Context window status -- {self.model}")
        plt.tight_layout()
        plt.show()


