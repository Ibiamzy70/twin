class SimpleRAGRetriever:
    """
    Retrieval half of RAG. Bag-of-words count vectors (not trained
    embeddings) compared with cosine similarity -- deliberately simple and
    self-contained, per the Ex.1 decision to keep this independent of the
    embeddings exercise set's build_embeddings()/dim constraints.

    Exception convention (deliberate, distinct by kind of failure):
      - RuntimeError: process() called before add_documents() -- a *state*
        problem (wrong order of operations), not a bad-argument problem.
      - ValueError/TypeError: bad arguments (None, wrong type, empty string).
      - A zero-vocabulary-overlap query is NOT an error: it returns
        [(None, 0.0)], since "nothing matched" is normal retriever behavior.
    """

    def __init__(self):
        self.data: List[str] = []
        self.vocab: List[str] = []
        self.doc_vectors: List[np.ndarray] = []
        self._doc_matrix: Optional[np.ndarray] = None
        self._doc_norms: Optional[np.ndarray] = None

    def add_documents(self, documents: List[str]):
        if not isinstance(documents, list) or not documents:
            raise ValueError("documents must be a non-empty list of strings")
        if not all(isinstance(d, str) and d.strip() for d in documents):
            raise ValueError("every document must be a non-empty string")

        self.data = documents
        tokenized = [doc.lower().split() for doc in documents]
        vocab_set = set()
        for tokens in tokenized:
            vocab_set.update(tokens)
        self.vocab = sorted(vocab_set)
        self.doc_vectors = [self._vectorize(tokens) for tokens in tokenized]

        # cached once per add_documents() call, reused by every process()
        # call after this -- avoids re-stacking/re-normalizing the whole
        # knowledge base on every single query (performance bonus).
        self._doc_matrix = np.stack(self.doc_vectors) if self.doc_vectors else None
        self._doc_norms = (np.linalg.norm(self._doc_matrix, axis=1)
                           if self._doc_matrix is not None else None)

    def _vectorize(self, tokens: List[str]) -> np.ndarray:
        counts = Counter(tokens)
        return np.array([counts.get(word, 0) for word in self.vocab], dtype=float)

    def process(self, input_data, top_n: int = 1) -> List[Tuple[Optional[str], float]]:
        if input_data is None:
            raise ValueError("input_data cannot be None")
        if not isinstance(input_data, str):
            raise TypeError(f"Expected str, got {type(input_data).__name__}")
        if input_data.strip() == "":
            raise ValueError("input_data cannot be an empty string")
        if not self.data:
            raise RuntimeError("Knowledge base is empty. Call add_documents() first.")
        if top_n <= 0:
            raise ValueError(f"top_n must be positive, got {top_n}")

        query_tokens = input_data.lower().split()
        query_vector = self._vectorize(query_tokens)
        query_norm = np.linalg.norm(query_vector)
        if query_norm == 0:
            return [(None, 0.0)]

        # vectorized: one matrix-vector product against the whole knowledge
        # base instead of a Python loop over documents (see benchmark()).
        raw = self._doc_matrix @ query_vector
        sims = np.where(self._doc_norms == 0, 0.0, raw / (self._doc_norms * query_norm + 0.0))
        # note: doc_norm==0 rows are forced to exactly 0.0 above (matching
        # the original per-document guard), not a small-epsilon approximation.
        scores = list(zip(self.data, sims.tolist()))
        scores.sort(key=lambda x: x[1], reverse=True)
        return scores[:top_n]


# =====================================================================
# 3. EXERCISE 2: load_and_preprocess (document loading + preprocessing)
# =====================================================================
def load_and_preprocess(data: List[Dict[str, str]], clean: bool = True, extract: bool = True,
                        chunk: bool = True, chunk_strategy: str = "smart",
                        max_chunk_size: int = 100, **kwargs) -> Dict[str, Any]:
    """
    Loads a batch of raw documents (already in memory -- reading from disk/
    URL/database is explicitly out of scope here) and preprocesses them for
    a RAG knowledge base: clean -> extract structured data -> chunk.
    Bad documents are skipped and recorded by index and reason, not raised,
    so one malformed item doesn't stop the whole batch (same graceful-
    degradation rule as the rest of the project).
    """
    if data is None:
        raise ValueError("data cannot be None. Pass a list of document dicts.")
    if not isinstance(data, list):
        raise TypeError(f"data must be a list, got {type(data).__name__}.")
    if len(data) == 0:
        raise ValueError("data is empty. Provide at least one document.")
    if chunk_strategy not in ChunkingSystem.STRATEGIES:
        raise ValueError(f"chunk_strategy must be one of {ChunkingSystem.STRATEGIES}, got '{chunk_strategy}'.")
    if max_chunk_size <= 0:
        raise ValueError(f"max_chunk_size must be positive, got {max_chunk_size}.")

    chunker = (ChunkingSystem(strategy=chunk_strategy, max_chunk_size=max_chunk_size,
                              words_per_chunk=max_chunk_size,
                              overlap=min(10, max_chunk_size - 1)) if chunk else None)

    processed_docs, skipped = [], []
    for i, doc in enumerate(data):
        if not isinstance(doc, dict):
            skipped.append({"index": i, "reason": f"expected dict, got {type(doc).__name__}"})
            continue
        if "text" not in doc:
            skipped.append({"index": i, "reason": "missing required 'text' key"})
            continue
        if not isinstance(doc["text"], str):
            skipped.append({"index": i, "reason": f"'text' must be str, got {type(doc['text']).__name__}"})
            continue
        if doc["text"].strip() == "":
            skipped.append({"index": i, "reason": "'text' is empty or whitespace-only"})
            continue

        source = doc.get("source", f"document_{i}")
        text = doc["text"]
        original_char_count = len(text)

        if clean:
            text = re.sub(r"[ \t]+", " ", text)
            text = re.sub(r"\n\s*\n+", "\n\n", text)
            text = text.strip()

        extracted = extract_profile_data(text) if extract else {}
        chunks = chunker.chunk(text, source=source) if chunk else []

        processed_docs.append({
            "index": i, "source": source, "original_char_count": original_char_count,
            "processed_char_count": len(text), "text": text,
            "extracted_data": extracted, "chunks": chunks, "chunk_count": len(chunks),
        })

    return {"total_input": len(data), "processed_count": len(processed_docs),
            "skipped_count": len(skipped), "documents": processed_docs, "skipped": skipped}


