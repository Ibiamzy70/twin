import unicodedata

class HardenedInjectionDetector(PromptInjectionDetector):
    """
    Fixes four concrete gaps found in red-teaming:
    1. Confidence threshold let single-pattern matches through.
    2. Pattern list only caught exact phrasing, not synonyms.
    3. No normalization — leetspeak and zero-width chars evaded every regex.
    4. No coverage for jailbreak-persona attacks (DAN, "developer mode", etc).
    """

    LEET_MAP = str.maketrans({"0": "o", "1": "i", "3": "e", "4": "a", "5": "s", "7": "t", "@": "a"})

    def __init__(self):
        super().__init__()
        # Broaden vocabulary: synonyms for the override/ignore family
        self.suspicious_patterns += [
            r'disregard\s+(your\s+)?(guidelines|rules|directives|constraints)',
            r'new\s+directive',
            r'no\s+restrictions',
            r'without\s+(any\s+)?restrictions',
            r'developer\s+mode',
            r'\bdan\b',                         # "DAN" jailbreak persona
            r'do\s+anything\s+now',
            r'unlock(ed)?\s+mode',
            r'bypass\s+(your\s+)?(rules|restrictions|filters)',
            r'pretend\s+you\s+(have\s+no|are\s+not)',
            r'act\s+as\s+(an?\s+)?(unrestricted|uncensored)',
        ]

    def _normalize(self, text: str) -> str:
        """Strip zero-width/invisible chars, normalize unicode, de-leet."""
        text = unicodedata.normalize("NFKC", text)
        # remove zero-width space, zero-width joiner/non-joiner, BOM
        text = re.sub(r'[\u200b\u200c\u200d\ufeff]', '', text)
        deleeted = text.lower().translate(self.LEET_MAP)
        return deleeted

    def detect(self, text: str) -> Dict[str, Any]:
        normalized = self._normalize(text)

        detected_patterns = [p for p in self.suspicious_patterns if re.search(p, normalized)]
        is_very_long = len(text) > 5000
        has_many_delimiters = text.count('---') > 3 or text.count('###') > 3

        # Fix: ANY single real pattern match is itself enough to flag —
        # don't require stacking three signals before crossing the line.
        is_suspicious = len(detected_patterns) > 0 or is_very_long or has_many_delimiters

        confidence = min(
            len(detected_patterns) * 0.4 +            # raised per-match weight
            (0.3 if is_very_long else 0) +
            (0.3 if has_many_delimiters else 0),
            1.0
        )

        return {
            'is_injection': is_suspicious,
            'detected_patterns': detected_patterns,
            'flags': {
                'suspicious_phrases': len(detected_patterns) > 0,
                'excessive_length': is_very_long,
                'delimiter_abuse': has_many_delimiters,
            },
            'confidence': confidence,
        }


class HardenedSecureDigitalTwin(SecureDigitalTwin):
    def __init__(self, name: str, system_prompt: str):
        super().__init__(name, system_prompt)
        self.detector = HardenedInjectionDetector()  # swap in the fixed detector

    def chat(self, user_input: str) -> str:
        detection = self.detector.detect(user_input)
        # Fix: lower the action threshold too, since a single real match
        # now correctly signals 0.4 confidence, not 0.3 — block at >0.3
        if detection['is_injection'] and detection['confidence'] > 0.3:
            self.blocked_attempts.append({
                'input': user_input, 'detection': detection, 'timestamp': 'now'
            })
            return "I detected a potentially unsafe input. Please rephrase your request."

        clean_input = self.defense.sanitize_input(user_input)
        response = f"I received your message: {clean_input[:50]}..."
        output_check = self.defense.validate_output(response)
        if not output_check['is_safe']:
            return "I apologize, but I cannot generate that response."
        return response

