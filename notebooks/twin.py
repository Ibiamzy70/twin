class TokenLimitChecker:
    """
    Basic tool for understanding token limits and context windows.
    Estimates token count and checks it against a model's context window.
    """

    def __init__(self, context_window: int = 8192, chars_per_token: float = 4.0):
        self.context_window = context_window
        self.chars_per_token = chars_per_token
        self.data = []

    def process(self, input_data):
        """
        Estimate the token count of input_data and check it against
        the context window limit.
        """
        # 4. Error handling for edge cases
        if input_data is None:
            raise ValueError("input_data cannot be None")
        if not isinstance(input_data, str):
            raise TypeError(f"Expected str, got {type(input_data).__name__}")
        if input_data.strip() == "":
            return {
                "text": input_data,
                "char_count": 0,
                "estimated_tokens": 0,
                "context_window": self.context_window,
                "fits": True,
                "usage_percent": 0.0,
            }

        char_count = len(input_data)
        estimated_tokens = round(char_count / self.chars_per_token)
        fits = estimated_tokens <= self.context_window
        usage_percent = round((estimated_tokens / self.context_window) * 100, 2)

        result = {
            "text": input_data,
            "char_count": char_count,
            "estimated_tokens": estimated_tokens,
            "context_window": self.context_window,
            "fits": fits,
            "usage_percent": usage_percent,
        }

        self.data.append(result)
        return result


