class EvaluationMetrics:
    '''Calculate metrics for AI outputs.'''

    @staticmethod
    def accuracy(results: List[Dict]) -> float:
        '''Calculate accuracy (% passed).'''
        if not results:
            return 0.0
        passed = sum(1 for r in results if r['passed'])
        return passed / len(results)

    @staticmethod
    def check_hallucination(output: str, context: str) -> bool:
        '''Check if output contains unsupported claims.

        v2: strips punctuation (via regex word extraction instead of
        .split()) and removes the fixed JSON schema vocabulary the twin's
        system prompt always produces, so structural keys like
        "missing_information" or "contains_guessing" don't get counted as
        hallucinated content just because they aren't literal words from
        the raw profile/history/temporal_patterns context.
        '''
        output_words = set(re.findall(r"[a-z']+", output.lower())) - JSON_SCHEMA_WORDS
        context_words = set(re.findall(r"[a-z']+", context.lower()))

        unique_words = output_words - context_words
        hallucination_ratio = len(unique_words) / len(output_words) if output_words else 0

        return hallucination_ratio > 0.7  # Threshold

    @staticmethod
    def relevance_score(query: str, response: str) -> float:
        '''Calculate relevance (0-1).'''
        query_words = set(query.lower().split())
        response_words = set(response.lower().split())

        # Jaccard similarity
        intersection = query_words & response_words
        union = query_words | response_words

        return len(intersection) / len(union) if union else 0.0

