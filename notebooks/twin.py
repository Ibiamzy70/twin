import string

def clean_text(text):
    # 1. Remove extra whitespace (leading/trailing + collapse internal multiple spaces)
    text = " ".join(text.split())

    # 2. Convert to lowercase
    text = text.lower()

    # 3. Remove punctuation
    text = text.translate(str.maketrans('', '', string.punctuation))

    # 4. Remove stop words
    stop_words = {"the", "a", "an", "is", "are", "and", "in", "on", "at", "to", "of", "for"}
    words = text.split()
    words = [word for word in words if word not in stop_words]
    cleaned = " ".join(words)

    return cleaned


