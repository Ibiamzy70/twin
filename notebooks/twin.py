        naive.sort(key=lambda x: x[1], reverse=True)
        fast = self.r.process(query, top_n=3)
        for (d1, s1), (d2, s2) in zip(naive, fast):
            self.assertEqual(d1, d2)
            self.assertAlmostEqual(s1, s2, places=6)


