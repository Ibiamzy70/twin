class SafeDigitalTwin:
    """Digital twin with full safety guardrails: content filtering, PII
    detection/redaction, rate limiting, output validation, and violation
    logging."""

    def __init__(self, name: str, max_calls_per_minute: int = 10,
                 llm_fn: Optional[callable] = None):
        self.name = name
        self.validator = OutputValidator()
        self.content_filter = ContentFilter()
        self.pii_detector = PIIDetector()
        self.rate_limiter = RateLimiter(max_calls=max_calls_per_minute, window_seconds=60.0)
        self.violation_log = ViolationLog()
        # Optional real model call (e.g. real_twin_ai). Falls back to an
        # echo mock if not provided, so this class is testable standalone.
        self.llm_fn = llm_fn or (lambda text: f"I received: {text}")

    def _process_input(self, user_input: str, identifier: str) -> Optional[str]:
        """Filter and redact user input. Returns None if blocked."""
        filter_result = self.content_filter.filter(user_input)

        if not filter_result["is_safe"]:
            self.violation_log.record(
                source="input", identifier=identifier, violation_type="content_filter",
                details={"profanity": filter_result["profanity_violations"],
                         "sensitive": filter_result["sensitive_topics"],
                         "domain": filter_result["domain_topics"]},
                text_snippet=user_input,
            )
            return None

        pii_check = self.pii_detector.detect(user_input)
        if pii_check["has_pii"]:
            self.violation_log.record(
                source="input", identifier=identifier, violation_type="pii_detected",
                details={"types": pii_check["pii_types"]}, text_snippet=user_input,
            )
            # Redact rather than block — PII in input is usually not malicious,
            # just something that shouldn't be forwarded to the model as-is.
            return self.pii_detector.redact(user_input)

        return user_input

    def _generate_response(self, filtered_input: str) -> str:
        """Generate AI response via the attached llm_fn (or the mock echo)."""
        return self.llm_fn(filtered_input)

    def _process_output(self, response: str, identifier: str) -> str:
        """Validate and process output before returning it to the user."""
        validation = self.validator.validate(response)

        if not validation["is_valid"]:
            self.violation_log.record(
                source="output", identifier=identifier, violation_type="output_validation",
                details={"issues": validation["issues"]}, text_snippet=response,
            )
            # If it's PII specifically, redact and retry validation rather
            # than discarding a response that might otherwise be fine.
            if any("PII" in issue for issue in validation["issues"]):
                redacted = self.pii_detector.redact(response)
                revalidate = self.validator.validate(redacted)
                if revalidate["is_valid"]:
                    response = redacted
                else:
                    return "I apologize, but I cannot provide that response. How else can I help?"
            else:
                return "I apologize, but I cannot provide that response. How else can I help?"

        if validation["needs_disclaimer"]:
            response = self.validator.add_disclaimer(response, response)

        return response

    def chat(self, user_input: str, identifier: str = "default") -> str:
        """Safe chat with full pipeline: rate limit -> input filter -> PII
        redact -> generate -> output validate -> disclaimer."""
        if not self.rate_limiter.allow(identifier):
            status = self.rate_limiter.check(identifier)
            self.violation_log.record(
                source="input", identifier=identifier, violation_type="rate_limit_exceeded",
                details={"retry_after": status["retry_after"]}, text_snippet=user_input,
            )
            return f"Rate limit exceeded. Please try again in {status['retry_after']}s."

        filtered_input = self._process_input(user_input, identifier)
        if filtered_input is None:
            return "I cannot process that input. Please rephrase."

        response = self._generate_response(filtered_input)
        safe_response = self._process_output(response, identifier)
        return safe_response


