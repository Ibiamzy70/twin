@dataclass
class Block:
    type: str                      # heading paragraph quote list keyvalue table code log_entry
    text: str
    section: Tuple[str, ...] = ()
    meta: Dict[str, Any] = field(default_factory=dict)
    index_text: Optional[str] = None

    @property
    def itext(self) -> str:
        return self.index_text if self.index_text is not None else self.text


def detect_format(text: str, name: str = "") -> str:
    ext = name.lower().rsplit(".", 1)[-1] if "." in name else ""
    if ext in ("md", "markdown"):
        return "markdown"
    if ext == "log":
        return "log"
    lines = [l for l in text.splitlines() if l.strip()][:200]
    if lines and sum(1 for l in lines if LOG_RE.match(l)) / len(lines) > 0.5:
        return "log"
    if (re.search(r"^#{1,6}\s+\S", text, re.M) or re.search(r"^\s{0,3}(```|~~~)", text, re.M)
            or re.search(r"^\s*\|?\s*:?-{2,}:?\s*\|", text, re.M) or text.startswith("---\n")):
        return "markdown"
    return "text"


def parse_front_matter(text: str) -> Tuple[Dict[str, str], str]:
    if not text.startswith("---\n"):
        return {}, text
    end = text.find("\n---", 4)
    if end == -1:
        return {}, text
    meta = {}
    for line in text[4:end].split("\n"):
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip().strip("\"'")
    return meta, text[end + 4:].lstrip("\n")


def render_table(header: List[str], rows: List[List[str]]) -> str:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(r) + " |" for r in rows]
    return "\n".join(lines)


def make_table_block(header, rows, section, **extra) -> Block:
    header = [h or f"col{i + 1}" for i, h in enumerate(header)]
    width = len(header)
    rows = [(r + [""] * width)[:width] for r in rows]
    records = [dict(zip(header, r)) for r in rows]
    index_text = "\n".join("; ".join(f"{h}: {v}" for h, v in zip(header, r) if v) for r in rows)
    meta = {"header": header, "rows": rows, "records": records, "n_rows": len(rows), **extra}
    return Block("table", render_table(header, rows), section, meta, f"table {' '.join(header)}\n{index_text}")


def make_code_block(lang, code, section, **extra) -> Block:
    fence = "```"
    while fence in code:
        fence += "`"
    return Block("code", f"{fence}{lang}\n{code}\n{fence}", section,
                 {"lang": lang, "code": code, **extra}, f"{lang} code\n{code}")


def _split_row(line: str) -> List[str]:
    s = line.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    return [clean_inline(c.replace("\\|", "|")) for c in re.split(r"(?<!\\)\|", s)]


def _is_table_start(lines: List[str], i: int) -> bool:
    return (i + 1 < len(lines) and "|" in lines[i] and "|" in lines[i + 1]
            and bool(TABLE_SEP_RE.match(lines[i + 1])))


def _ascii_table(lines: List[str], i: int):
    """Whitespace-aligned table: >=3 consistent rows split by 2+ spaces."""
    j, ncols, rows = i, None, []
    while j < len(lines):
        l = lines[j]
        if not l.strip():
            break
        if re.fullmatch(r"[\s\-=+|]+", l):
            j += 1
            continue
        cells = re.split(r"\s{2,}", l.strip())
        if len(cells) < 2 or (ncols and len(cells) != ncols):
            break
        ncols = ncols or len(cells)
        rows.append([clean_inline(c) for c in cells])
        j += 1
    return (rows, j) if len(rows) >= 3 else None


def _starts_block(lines: List[str], j: int) -> bool:
    l = lines[j]
    return bool(FENCE_RE.match(l) or HEADING_RE.match(l) or HR_RE.match(l) or QUOTE_RE.match(l)
                or LIST_RE.match(l) or _is_table_start(lines, j))


def parse_log(text: str) -> List[Block]:
    blocks: List[Block] = []
    cur, pre = None, []

    def finish(c):
        ts = c["ts"].replace(",", ".").replace("T", " ")
        cont = "\n".join(c["cont"])
        msg = c["msg"]
        comp = re.match(r"^\[([\w.\-]+)\]\s*", msg)
        level = "WARN" if c["level"].upper() == "WARNING" else c["level"].upper()
        body = c["first"] + ("\n" + cont if cont else "")
        blocks.append(Block("log_entry", body, (ts[:10],), {
            "ts": ts, "level": level, "component": comp.group(1) if comp else "",
            "has_trace": bool(cont), "entity_text": msg + ("\n" + cont if cont else "")},
            f"{level} {msg}" + ("\n" + cont if cont else "")))

    for line in text.split("\n"):
        m = LOG_RE.match(line)
        if m:
            if cur:
                finish(cur)
            cur = {"ts": m.group("ts"), "level": m.group("level"), "msg": m.group("msg"),
                   "first": line.rstrip(), "cont": []}
        elif cur is not None:
            if line.strip():
                cur["cont"].append(line.rstrip())
        elif line.strip():
            pre.append(line.strip())
    if cur:
        finish(cur)
    if pre:
        blocks.insert(0, Block("paragraph", clean_inline(" ".join(pre)), ("preamble",)))
    return blocks


def parse_blocks(text: str, fmt: str) -> List[Block]:
    if fmt == "log":
        return parse_log(text)
    plain = fmt == "text"
    lines = text.split("\n")
    n, i = len(lines), 0
    blocks: List[Block] = []
    stack: List[Tuple[int, str]] = []

    def section() -> Tuple[str, ...]:
        return tuple(t for _, t in stack)

    def heading(level: int, title: str):
        while stack and stack[-1][0] >= level:
            stack.pop()
        stack.append((level, title))
        blocks.append(Block("heading", title, section(), {"level": level}))

    while i < n:
        line = lines[i]
        if not line.strip():
            i += 1
            continue

        # fenced code -------------------------------------------------
        m = FENCE_RE.match(line)
        if m:
            fence, lang = m.group(1), m.group(2)
            closing = re.compile(r"^\s{0,3}" + re.escape(fence[0]) + "{%d,}\\s*$" % len(fence))
            j, body, closed = i + 1, [], False
            while j < n:
                if closing.match(lines[j]):
                    closed = True
                    break
                body.append(lines[j])
                j += 1
            code = textwrap.dedent("\n".join(body)).rstrip()
            blocks.append(make_code_block(lang or guess_language(code), code, section(), unclosed=not closed))
            i = j + 1 if closed else j
            continue

        # headings ----------------------------------------------------
        m = HEADING_RE.match(line)
        if m:
            heading(len(m.group(1)), clean_inline(m.group(2)))
            i += 1
            continue
        if HR_RE.match(line):
            i += 1
            continue

        # tables ------------------------------------------------------
        if _is_table_start(lines, i):
            header = _split_row(line)
            j, rows = i + 2, []
            while j < n and lines[j].strip() and "|" in lines[j]:
                rows.append(_split_row(lines[j]))
                j += 1
            blocks.append(make_table_block(header, rows, section()))
            i = j
            continue

        # plain-text specials ----------------------------------------
        if plain:
            if line.startswith(("    ", "\t")):
                j, buf = i, []
                while j < n and (lines[j].startswith(("    ", "\t")) or
                                 (not lines[j].strip() and j + 1 < n and lines[j + 1].startswith(("    ", "\t")))):
                    buf.append(lines[j])
                    j += 1
                if sum(1 for b in buf if b.strip()) >= 2:
                    code = textwrap.dedent("\n".join(buf)).rstrip()
                    blocks.append(make_code_block(guess_language(code), code, section()))
                    i = j
                    continue
            at = _ascii_table(lines, i)
            if at:
                rows, j = at
                blocks.append(make_table_block(rows[0], rows[1:], section(), ascii=True))
                i = j
                continue
        if (i + 1 < n and re.match(r"^\s{0,3}(=+|-+)\s*$", lines[i + 1]) and len(lines[i + 1].strip()) >= 3
                and not LIST_RE.match(line) and "|" not in line):
            heading(1 if "=" in lines[i + 1] else 2, clean_inline(line))
            i += 2
            continue
        if plain and CAPS_RE.match(line.strip()) and len(re.findall(r"[A-Z]", line)) >= 3:
            heading(2, line.strip().rstrip(":").title())
            i += 1
            continue

        # quotes ------------------------------------------------------
        if QUOTE_RE.match(line):
            j, buf = i, []
            while j < n and QUOTE_RE.match(lines[j]):
                buf.append(QUOTE_RE.match(lines[j]).group(1).strip())
                j += 1
            blocks.append(Block("quote", clean_inline(" ".join(b for b in buf if b)), section()))
            i = j
            continue

        # lists -------------------------------------------------------
        if LIST_RE.match(line):
            j, items = i, []
            while j < n:
                l = lines[j]
                if LIST_RE.match(l):
                    items.append(l.rstrip())
                    j += 1
                elif not l.strip() and j + 1 < n and LIST_RE.match(lines[j + 1]):
                    j += 1
                elif l.strip() and l.startswith((" ", "\t")) and items and not FENCE_RE.match(l):
                    items[-1] += " " + l.strip()
                    j += 1
                else:
                    break
            rendered = []
            for it in items:
                mm = LIST_FULL_RE.match(it)
                rendered.append(mm.group(1) + clean_inline(mm.group(2)) if mm else clean_inline(it))
            blocks.append(Block("list", "\n".join(rendered), section(), {"n_items": len(rendered)}))
            i = j
            continue

        # paragraph / key-value --------------------------------------
        j, buf = i, []
        while j < n and lines[j].strip() and (j == i or not _starts_block(lines, j)):
            buf.append(lines[j].strip())
            j += 1
        if len(buf) >= 2 and all(KV_RE.match(b) for b in buf):
            pairs = {b.split(":", 1)[0].strip(): clean_inline(b.split(":", 1)[1]) for b in buf}
            blocks.append(Block("keyvalue", "\n".join(f"{k}: {v}" for k, v in pairs.items()), section(),
                                {"pairs": pairs}))
        else:
            blocks.append(Block("paragraph", clean_inline(" ".join(buf)), section()))
        i = j
    return [b for b in blocks if b.type == "heading" or b.text.strip()]


