        sanitized = re.sub(r'\[system.*?\]', '', sanitized, flags=re.IGNORECASE)

        # Limit length
        if len(sanitized) > 2000:
            sanitized = sanitized[:2000] + '... [truncated]'

        # Escape special characters that might confuse the AI
