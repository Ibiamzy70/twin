class EmbeddingPipeline:
    """
    Production pipeline for building word embeddings from digital twin
    text data (activity logs, profile fields, notes) and inspecting them.

    Parameters
    ----------
    dim : int
        Target embedding dimension.
    window : int
        Context window size for co-occurrence counting.
    min_count : int
        Minimum word frequency to be included in the vocabulary.

    Example
    -------
    >>> pipeline = EmbeddingPipeline(dim=3, window=2)
    >>> result = pipeline.run(documents, source="activity_history")
    >>> pipeline.visualize(result)
    >>> pipeline.nearest(result, "running", top_n=3)
    """

    def __init__(self, dim: int = 3, window: int = 2, min_count: int = 1):
        if dim <= 0:
            raise ValueError(f"dim must be positive, got {dim}.")
        if window <= 0:
            raise ValueError(f"window must be positive, got {window}.")
        if min_count <= 0:
            raise ValueError(f"min_count must be positive, got {min_count}.")

        self.dim = dim
        self.window = window
        self.min_count = min_count
        self.run_history: List[Dict[str, Any]] = []
        logger.info(f"Pipeline initialized: dim={dim}, window={window}, min_count={min_count}")

    # -----------------------------------------------------------------
    # Core pipeline
    # -----------------------------------------------------------------
    def run(self, documents: List[str], source: str = "unknown") -> Dict[str, Any]:
        """
        Build embeddings from a list of text documents.

        Returns a dict with: source, timestamp, vocabulary, embeddings,
        co-occurrence matrix, and any warnings/errors encountered.
        """
        run_id = len(self.run_history) + 1
        timestamp = datetime.now().isoformat(timespec="seconds")
        logger.info(f"[run {run_id}] starting | source={source} | {len(documents) if isinstance(documents, list) else 'N/A'} docs")

        result = {
            "run_id": run_id,
            "source": source,
            "timestamp": timestamp,
            "vocab_size": 0,
            "embeddings": {},
            "warnings": [],
            "errors": [],
        }

        try:
            self._validate_input(documents)
        except (ValueError, TypeError) as e:
            logger.error(f"[run {run_id}] input validation failed: {e}")
            result["errors"].append(str(e))
            self.run_history.append(result)
            return result

        try:
            built = build_embeddings(documents, dim=self.dim, window=self.window,
                                      min_count=self.min_count)
            result["vocab_size"] = built["vocab_size"]
            result["embeddings"] = built["embeddings"]
            result["vocabulary"] = built["vocabulary"]

            if built["vocab_size"] < 10:
                warning = f"Small vocabulary ({built['vocab_size']} words) — embeddings may not be meaningful."
                logger.warning(f"[run {run_id}] {warning}")
                result["warnings"].append(warning)

            logger.info(f"[run {run_id}] built embeddings for {built['vocab_size']} words")

        except (ValueError, TypeError) as e:
            logger.error(f"[run {run_id}] embedding build failed: {e}")
            result["errors"].append(f"embedding build failed: {e}")
        except np.linalg.LinAlgError as e:
            logger.error(f"[run {run_id}] SVD failed to converge: {e}")
            result["errors"].append(f"SVD failed: {e}")

        self.run_history.append(result)
        logger.info(f"[run {run_id}] complete | warnings={len(result['warnings'])} "
                    f"errors={len(result['errors'])}")
        return result

    # -----------------------------------------------------------------
    # Helpers
    # -----------------------------------------------------------------
    def _validate_input(self, documents):
        if documents is None:
            raise ValueError("documents cannot be None")
        if not isinstance(documents, list):
            raise TypeError(f"documents must be a list, got {type(documents).__name__}")
        if len(documents) == 0:
            raise ValueError("documents is empty")

    def nearest(self, result: Dict[str, Any], word: str, top_n: int = 3):
        """Look up the most similar words to `word` from a run() result."""
        if not result.get("embeddings"):
            logger.warning("No embeddings available for this run — cannot compute similarity.")
            return []
        try:
            return most_similar(result["embeddings"], word, top_n=top_n)
        except KeyError as e:
            logger.error(f"nearest() failed: {e}")
            return []

    # -----------------------------------------------------------------
    # Visualization
    # -----------------------------------------------------------------
    def visualize(self, result: Dict[str, Any]) -> None:
        """
        Project embeddings down to 2D (via SVD) and scatter-plot them,
        with each point labeled by its word.
        """
        embeddings = result.get("embeddings", {})
        if not embeddings:
            logger.warning("No embeddings to visualize for this run.")
            return

        words = list(embeddings.keys())
        vectors = np.array([embeddings[w] for w in words])

        # Project to 2D for plotting, regardless of the original `dim`
        if vectors.shape[1] > 2:
            U, S, _ = np.linalg.svd(vectors - vectors.mean(axis=0))
            coords = U[:, :2] * S[:2]
        else:
            coords = vectors[:, :2] if vectors.shape[1] == 2 else np.column_stack([vectors[:, 0], np.zeros(len(vectors))])

        fig, ax = plt.subplots(figsize=(10, 6))
        ax.scatter(coords[:, 0], coords[:, 1], color="steelblue")
        for i, word in enumerate(words):
            ax.annotate(word, (coords[i, 0], coords[i, 1]), fontsize=9, xytext=(4, 4),
                        textcoords="offset points")

        ax.set_title(f"Word Embedding Space ({result['source']}, {len(words)} words)")
        ax.set_xlabel("Component 1")
        ax.set_ylabel("Component 2")
        ax.axhline(0, color="gray", linewidth=0.5)
        ax.axvline(0, color="gray", linewidth=0.5)

        plt.tight_layout()
        plt.show()

    # -----------------------------------------------------------------
    # Summary / debugging
    # -----------------------------------------------------------------
    def summary(self) -> None:
        """Print a summary of every run so far — useful for debugging."""
        if not self.run_history:
            print("No runs yet.")
            return
        for r in self.run_history:
            print(f"Run {r['run_id']} | {r['source']} | {r['timestamp']}")
            print(f"  vocab_size: {r['vocab_size']} | warnings: {len(r['warnings'])} "
                  f"| errors: {len(r['errors'])}")
            if r["errors"]:
                print(f"  ⚠️ errors: {r['errors']}")


