class TokenEstimator:
    """Two independent rough estimators (chars/4 and words*1.3), cached so a
    repeated string is not re-scanned. Both are approximations of BPE-style
    tokenization (see the notebook's tokenization section); neither calls a
    real tokenizer or the Groq API."""

    def __init__(self, chars_per_token: float = DEFAULT_CHARS_PER_TOKEN, words_per_token: float = 0.75):
        if chars_per_token <= 0:
            raise ValueError(f"chars_per_token must be positive, got {chars_per_token}.")
        if words_per_token <= 0:
            raise ValueError(f"words_per_token must be positive, got {words_per_token}.")
        self.chars_per_token = chars_per_token
        self.words_per_token = words_per_token
        self._cache: Dict[Tuple[str, float, float], dict] = {}
        self.calls = 0
        self.cache_hits = 0

    def estimate(self, text) -> dict:
        """Returns {char_count, word_count, estimated_tokens, low, high}.
        Raises ValueError on None, TypeError on non-str -- same contract as
        TokenLimitChecker.process() in Exercise 1."""
        if text is None:
            raise ValueError("text cannot be None")
        if not isinstance(text, str):
            raise TypeError(f"Expected str, got {type(text).__name__}")

        self.calls += 1
        key = (text, self.chars_per_token, self.words_per_token)
        cached = self._cache.get(key)
        if cached is not None:
            self.cache_hits += 1
            return cached

        if text.strip() == "":
            result = {"char_count": 0, "word_count": 0, "estimated_tokens": 0, "low": 0, "high": 0}
        else:
            char_count = len(text)
            word_count = len(text.split())
            by_chars = round(char_count / self.chars_per_token)
            by_words = round(word_count / self.words_per_token)
            result = {"char_count": char_count, "word_count": word_count,
                      "estimated_tokens": round((by_chars + by_words) / 2),
                      "low": min(by_chars, by_words), "high": max(by_chars, by_words)}
        # bound the cache so a long-running process can't grow it unboundedly
        if len(self._cache) >= 4096:
            self._cache.pop(next(iter(self._cache)))
        self._cache[key] = result
        return result

    def cache_info(self) -> dict:
        rate = round(self.cache_hits / self.calls, 3) if self.calls else 0.0
        return {"calls": self.calls, "cache_hits": self.cache_hits, "hit_rate": rate,
                "cache_size": len(self._cache)}


