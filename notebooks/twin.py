class TestTokenEstimator(unittest.TestCase):
    def setUp(self):
        self.est = TokenEstimator()

    def test_none_raises(self):
        with self.assertRaises(ValueError):
            self.est.estimate(None)

    def test_non_string_raises(self):
        with self.assertRaises(TypeError):
            self.est.estimate(12345)

    def test_empty_string_is_zero_not_error(self):
        r = self.est.estimate("   ")
        self.assertEqual(r["estimated_tokens"], 0)

    def test_normal_text_estimate(self):
        r = self.est.estimate("Hello! I love running at 6am every morning.")
        self.assertGreater(r["estimated_tokens"], 0)
        self.assertLessEqual(r["low"], r["estimated_tokens"])
        self.assertGreaterEqual(r["high"], r["estimated_tokens"])

    def test_cache_hits_on_repeat(self):
        text = "repeat me " * 20
        self.est.estimate(text)
        self.est.estimate(text)
        info = self.est.cache_info()
        self.assertEqual(info["calls"], 2)
        self.assertEqual(info["cache_hits"], 1)

    def test_invalid_chars_per_token(self):
        with self.assertRaises(ValueError):
            TokenEstimator(chars_per_token=0)


class TestContextWindowManager(unittest.TestCase):
    def setUp(self):
        self.mgr = ContextWindowManager(model="openai/gpt-oss-20b", reserved_output=100,
                                        safety_margin=0.0)

    def test_unknown_model_without_window_raises(self):
        with self.assertRaises(ValueError):
            ContextWindowManager(model="not-a-real-model")

    def test_reserved_output_ge_window_raises(self):
        with self.assertRaises(ValueError):
            ContextWindowManager(context_window=100, reserved_output=100)

    def test_add_message_invalid_role(self):
        with self.assertRaises(ValueError):
            self.mgr.add_message("bot", "hi")

    def test_add_message_none_content(self):
        with self.assertRaises(ValueError):
            self.mgr.add_message("user", None)

    def test_add_message_updates_budget(self):
        b0 = self.mgr.budget()["used_tokens"]
        self.mgr.add_message("user", "some text to add here")
        self.assertGreater(self.mgr.budget()["used_tokens"], b0)

    def test_trim_drop_oldest_respects_pinned(self):
        mgr = ContextWindowManager(context_window=2000, reserved_output=100, safety_margin=0.0)
        mgr.add_message("system", "SYSTEM " * 50, pinned=True)
        for i in range(5):
            mgr.add_message("user", f"message number {i} " * 60)
        result = mgr.trim(strategy="drop_oldest", target_percent=50)
        self.assertTrue(all(m.pinned for m in mgr.messages if m.role == "system"))
        self.assertGreaterEqual(len(result["dropped"]), 1)

    def test_trim_priority_keeps_high_priority(self):
        self.mgr.add_message("user", "low priority " * 300, priority=0)
        self.mgr.add_message("user", "high priority " * 300, priority=10)
        self.mgr.trim(strategy="drop_lowest_priority", target_percent=30)
        remaining_priorities = [m.priority for m in self.mgr.messages]
        if remaining_priorities:
            self.assertEqual(max(remaining_priorities), 10)

    def test_ingest_document_empty_is_valid(self):
        r = self.mgr.ingest_document("   ", source="empty.txt")
        self.assertEqual(r["chunks"], [])
        self.assertEqual(r["total_estimated_tokens"], 0)

    def test_ingest_document_none_raises(self):
        with self.assertRaises(ValueError):
            self.mgr.ingest_document(None)

    def test_ingest_document_produces_chunks(self):
        # smart chunking splits at paragraph breaks, so the test text needs them
        para = "This is a digital twin sentence about engineering work. " * 10
        long_text = (para + "\n\n") * 20
        r = self.mgr.ingest_document(long_text, source="log.txt", max_chunk_size=50)
        self.assertGreater(len(r["chunks"]), 1)
        self.assertTrue(all("estimated_tokens" in c for c in r["chunks"]))

    def test_build_messages_shape(self):
        self.mgr.add_message("user", "hello twin")
        msgs = self.mgr.build_messages(system_prompt="you are a helpful twin")
        self.assertEqual(msgs[0]["role"], "system")
        self.assertTrue(all(set(m.keys()) == {"role", "content"} for m in msgs))

    def test_from_twin_data_wrong_type_raises(self):
        with self.assertRaises(TypeError):
            ContextWindowManager.from_twin_data(user_profile="not a dict",
                                                activity_history=[], temporal_patterns={})

    def test_summarize_strategy_falls_back_without_summarizer(self):
        self.mgr.summarizer = None
        self.mgr.add_message("user", "x " * 4000)
        result = self.mgr.trim(strategy="summarize", target_percent=1)
        self.assertGreaterEqual(len(result["dropped"]), 1)

    def test_summarize_strategy_uses_summarizer_when_given(self):
        mgr = ContextWindowManager(model="openai/gpt-oss-20b", reserved_output=100,
                                   safety_margin=0.0, summarizer=lambda s: s[:20])
        mgr.add_message("user", "y " * 4000)
        result = mgr.trim(strategy="summarize", target_percent=1)
        self.assertGreaterEqual(len(result["summarized"]) + len(result["dropped"]), 1)

    def test_impossible_budget_flagged_not_crashed(self):
        mgr = ContextWindowManager(context_window=50, reserved_output=10, safety_margin=0.0)
        mgr.add_message("system", "pinned " * 100, pinned=True)
        result = mgr.trim(strategy="drop_oldest")
        self.assertFalse(result["budget"]["fits"])   # flagged, no exception


def run_tests(verbosity: int = 2):
    loader = unittest.TestLoader()
    suite = unittest.TestSuite()
    suite.addTests(loader.loadTestsFromTestCase(TestTokenEstimator))
    suite.addTests(loader.loadTestsFromTestCase(TestContextWindowManager))
    return unittest.TextTestRunner(verbosity=verbosity).run(suite)


