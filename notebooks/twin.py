from typing import List, Dict, Any

def estimate_tokens(data: List[Any],
                     context_window: int = 8192,
                     chars_per_token: float = 4.0,
                     skip_bad_items: bool = True,
                     **kwargs) -> Dict[str, Any]:
    """
    Token counting and estimation for a list of text items.

    Args:
        data: List of items to process (expected to be strings)
        context_window: Max tokens the target model can accept
        chars_per_token: Rough chars-per-token estimate (default ~4 for English)
        skip_bad_items: If True, skip invalid items and record them as errors
                        instead of raising. If False, raise on the first bad item.
        **kwargs: Reserved for future options (accepted but unused, so old
                   calls don't break if new parameters are added later)

    Returns:
        dict: Structured results, per-item estimates, and any errors found.
    """
    # 2. Parameter validation, with 3. helpful error messages
    if data is None:
        raise ValueError("data cannot be None. Pass a list of strings.")
    if not isinstance(data, list):
        raise TypeError(f"data must be a list, got {type(data).__name__}.")
    if len(data) == 0:
        raise ValueError("data is empty. Provide at least one item to process.")
    if context_window <= 0:
        raise ValueError(f"context_window must be positive, got {context_window}.")
    if chars_per_token <= 0:
        raise ValueError(f"chars_per_token must be positive, got {chars_per_token}.")

    items = []
    errors = []
    total_tokens = 0

    for i, item in enumerate(data):
        # Validate each item individually rather than assuming clean input
        if item is None:
            msg = f"item at index {i} is None"
            if skip_bad_items:
                errors.append({"index": i, "error": msg})
                continue
            raise ValueError(msg)

        if not isinstance(item, str):
            msg = f"item at index {i} is {type(item).__name__}, expected str"
            if skip_bad_items:
                errors.append({"index": i, "error": msg})
                continue
            raise TypeError(msg)

        if item.strip() == "":
            msg = f"item at index {i} is an empty or whitespace-only string"
            errors.append({"index": i, "error": msg})
            # Empty string is valid data (0 tokens), not fatal — still recorded below
            char_count = 0
            est_tokens = 0
        else:
            char_count = len(item)
            est_tokens = round(char_count / chars_per_token)

        total_tokens += est_tokens
        items.append({
            "index": i,
            "text_preview": item[:40] + ("..." if len(item) > 40 else ""),
            "char_count": char_count,
            "estimated_tokens": est_tokens,
            "fits_alone": est_tokens <= context_window,
        })

    return {
        "item_count": len(data),
        "valid_items": len(items),
        "skipped_items": len(errors),
        "total_estimated_tokens": total_tokens,
        "context_window": context_window,
        "fits_combined": total_tokens <= context_window,
        "usage_percent": round((total_tokens / context_window) * 100, 2),
        "items": items,
        "errors": errors,
    }


