def benchmark(n_messages: int = 500) -> dict:
    """Times add_message + trim over many messages, and reports the
    estimator's cache hit rate to show caching is actually saving work."""
    mgr = ContextWindowManager(model="openai/gpt-oss-20b", reserved_output=500, safety_margin=0.0)
    texts = [f"activity log entry number {i % 50} about coding and reviews" for i in range(n_messages)]
    t0 = time.perf_counter()
    for t in texts:
        mgr.add_message("user", t)
    add_time = time.perf_counter() - t0
    t0 = time.perf_counter()
    result = mgr.trim(strategy="drop_oldest", target_percent=80)
    trim_time = time.perf_counter() - t0
    return {"n_messages": n_messages, "add_time_s": round(add_time, 4), "trim_time_s": round(trim_time, 4),
            "dropped": len(result["dropped"]), "estimator_cache": mgr.estimator.cache_info()}


