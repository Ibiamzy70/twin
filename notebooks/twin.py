@dataclass
class Draft:
    key: tuple
    pieces: List[Block] = field(default_factory=list)
    words: int = 0
    overlap_text: str = ""
    overlap_words: int = 0
    closed_by: str = ""
    same_key_neighbor: bool = False


def _greedy(units: List[str], limit: int, joiner: str) -> List[str]:
    out, cur, w = [], [], 0
    for u in units:
        uw = wc(u)
        if cur and w + uw > limit:
            out.append(joiner.join(cur))
            cur, w = [], 0
        cur.append(u)
        w += uw
    if cur:
        out.append(joiner.join(cur))
    return out


class Chunker:
    """Packs blocks into chunks. Tables/code/log entries are atomic; if one must be
    split, tables repeat their header row and code parts are re-fenced."""

    def __init__(self, max_words=120, min_words=15, log_max_words=150, overlap_sentences=1, split_level=2):
        self.max_words, self.min_words = max_words, min_words
        self.log_max_words = log_max_words
        self.overlap_sentences = overlap_sentences
        self.split_level = split_level          # H1/H2 = hard boundaries, H3+ may share a chunk

    # ---- splitting oversize blocks -----------------------------------
    def _split_table(self, b: Block, limit: int) -> List[Block]:
        header, rows = b.meta["header"], b.meta["rows"]
        hw = wc(" ".join(header))
        groups, cur, w = [], [], hw
        for r in rows:
            rw = wc(" ".join(r))
            if cur and w + rw > limit:
                groups.append(cur)
                cur, w = [], hw
            cur.append(r)
            w += rw
        if cur:
            groups.append(cur)
        return [make_table_block(header, g, b.section, split=True, part=k + 1) for k, g in enumerate(groups)]

    def _split_code(self, b: Block, limit: int) -> List[Block]:
        lang, lines = b.meta["lang"], b.meta["code"].split("\n")
        groups, cur, w = [], [], 0
        for ln in lines:
            lw = wc(ln)
            if cur and w + lw > limit:
                blank = max((k for k, x in enumerate(cur) if not x.strip()), default=-1)
                if blank > len(cur) // 2:
                    groups.append(cur[:blank])
                    cur = cur[blank + 1:]
                else:
                    groups.append(cur)
                    cur = []
                w = sum(wc(x) for x in cur)
            cur.append(ln)
            w += lw
        if cur:
            groups.append(cur)
        codes = [c for c in ("\n".join(g).strip("\n") for g in groups) if c.strip()]
        return [make_code_block(lang, c, b.section, split=True, part=k + 1) for k, c in enumerate(codes)]

    def _explode(self, b: Block, limit: int) -> List[Block]:
        if b.type == "log_entry" or wc(b.text) <= limit:
            return [b]
        if b.type == "table":
            return self._split_table(b, limit)
        if b.type == "code":
            return self._split_code(b, limit)
        units, joiner = ((b.text.split("\n"), "\n") if b.type in ("list", "keyvalue")
                         else (split_sentences(b.text), " "))
        fixed = []
        for u in units:
            if wc(u) > limit:
                ws = u.split()
                fixed += [" ".join(ws[k:k + limit]) for k in range(0, len(ws), limit)]
            else:
                fixed.append(u)
        return [Block(b.type, g, b.section, {**b.meta, "split": True}) for g in _greedy(fixed, limit, joiner)]

    def _last_sentence(self, text: str, limit: int) -> str:
        s = split_sentences(text)
        return s[-1] if s and wc(s[-1]) <= max(1, limit // 4) else ""

    # ---- packing ------------------------------------------------------
    def build(self, blocks: List[Block], fmt: str) -> Tuple[List[Draft], Dict[str, int], int]:
        is_log = fmt == "log"
        limit = self.log_max_words if is_log else self.max_words
        drafts: List[Draft] = []
        state = {"cur": None, "seed": "", "seed_key": None}
        stats = {"atomic_total": 0, "atomic_split": 0, "blocks": 0}

        def close(reason: str):
            cur = state["cur"]
            if cur is None:
                return
            cur.closed_by = reason
            drafts.append(cur)
            last = cur.pieces[-1]
            state["seed"] = (self._last_sentence(last.text, limit)
                             if (not is_log and self.overlap_sentences and last.type in PROSE) else "")
            state["seed_key"], state["cur"] = cur.key, None

        for b in blocks:
            if b.type == "heading":
                continue
            stats["blocks"] += 1
            parts = self._explode(b, limit)
            if b.type in ("table", "code"):
                stats["atomic_total"] += 1
                stats["atomic_split"] += int(len(parts) > 1)
            key = () if is_log else tuple(b.section[:self.split_level])
            for p in parts:
                w = wc(p.text)
                if state["cur"] is not None and state["cur"].key != key:
                    close("boundary")
                cur = state["cur"]
                if cur is not None and cur.words + w > limit:
                    keep = (cur.pieces[-1].type in PROSE and cur.pieces[-1].text.rstrip().endswith(":")
                            and p.type in ("table", "code") and cur.words + w <= limit * 1.5)
                    if not keep:
                        close("size")
                if state["cur"] is None:
                    ov = state["seed"] if (state["seed"] and state["seed_key"] == key and p.type in PROSE) else ""
                    state["cur"] = Draft(key=key, overlap_text=ov, overlap_words=wc(ov), words=wc(ov))
                state["cur"].pieces.append(p)
                state["cur"].words += w
        close("end")

        merged: List[Draft] = []       # fold tiny tail chunks into their predecessor
        for d in drafts:
            own = d.words - d.overlap_words
            if (merged and merged[-1].key == d.key and own < self.min_words
                    and merged[-1].words + own <= limit * 1.25):
                prev = merged[-1]
                prev.pieces += d.pieces
                prev.words += own
                prev.closed_by = d.closed_by
            else:
                merged.append(d)
        for k, d in enumerate(merged):
            d.same_key_neighbor = ((k > 0 and merged[k - 1].key == d.key) or
                                   (k + 1 < len(merged) and merged[k + 1].key == d.key))
        return merged, stats, limit


