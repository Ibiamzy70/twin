LONG_DOCUMENT = """Digital twins are computational representations of a person's behavior, preferences and
likely next actions, built entirely from evidence the person has produced: profile data, activity history and
temporal patterns. A good digital twin never invents facts. It ranks predictions by confidence, separates
observed signals from inferred conclusions, and says plainly when evidence is missing or weak.

Building one in practice means solving a chain of smaller problems first: getting a reliable connection to a
language model, writing a system prompt that forces structured output, cleaning and chunking source text so it
fits inside a context window, and tracking that context window so a long conversation does not silently overflow
it. Context window management sits close to the end of that chain, but it touches almost everything upstream,
since every document, every turn of conversation and every retrieved chunk eventually has to fit inside the same
fixed budget of tokens.

A context window manager therefore needs to do three things well: estimate how many tokens a piece of text will
cost before it is sent, track a running budget across an entire conversation rather than one message at a time,
and decide what to drop, summarize or postpone when the budget runs out. None of this replaces a real tokenizer.
It is a best-effort estimate, used to catch problems early, not a guarantee of the exact count a model's API will
bill for."""


