    class ChunkingSystem:
        """Fallback copy (smart/paragraph/sentence/word strategies)."""
        STRATEGIES = ("sentence", "word", "paragraph", "smart")

        def __init__(self, strategy="smart", source="unknown", sentences_per_chunk=3,
                     words_per_chunk=50, overlap=10, max_chunk_size=50,
                     min_words=8, max_words=80):
            if strategy not in self.STRATEGIES:
                raise ValueError(f"Unknown strategy '{strategy}'. Choose from {self.STRATEGIES}")
            if overlap >= words_per_chunk:
                raise ValueError("overlap must be smaller than words_per_chunk")
            self.strategy, self.source = strategy, source
            self.sentences_per_chunk, self.words_per_chunk = sentences_per_chunk, words_per_chunk
            self.overlap, self.max_chunk_size = overlap, max_chunk_size
            self.min_words, self.max_words = min_words, max_words

        @staticmethod
        def _paragraphs(text):
            return [p.strip() for p in re.split(r"\n\s*\n", text.strip()) if p.strip()]

        @staticmethod
        def _sentences(text):
            return [s for s in re.split(r"(?<=[.!?])\s+", text.strip()) if s]

        def _by_sentence(self, text):
            sents = self._sentences(text)
            n = self.sentences_per_chunk
            return [" ".join(sents[i:i + n]) for i in range(0, len(sents), n)]

        def _by_word(self, text):
            words = text.split()
            step = self.words_per_chunk - self.overlap
            chunks = []
            for i in range(0, len(words), step):
                chunks.append(" ".join(words[i:i + self.words_per_chunk]))
                if i + self.words_per_chunk >= len(words):
                    break
            return chunks

        def _by_paragraph(self, text):
            return [" ".join(p.split()) for p in self._paragraphs(text)]

        def _by_smart(self, text):
            chunks, current = [], ""
            for para in self._paragraphs(text):
                para = " ".join(para.split())
                if current and len(current.split()) + len(para.split()) > self.max_chunk_size:
                    chunks.append(current)
                    current = self._sentences(current)[-1] + " " + para
                else:
                    current = f"{current} {para}".strip()
            if current:
                chunks.append(current)
            return chunks

        def _validate(self, text):
            issues, n = [], len(text.split())
            if n < self.min_words: issues.append(f"too small ({n} words)")
            if n > self.max_words: issues.append(f"too large ({n} words)")
            if not (text[0].isupper() or text[0].isdigit()): issues.append("starts mid-sentence")
            if text[-1] not in ".!?": issues.append("ends mid-sentence")
            return issues

        def chunk(self, text, source=None):
            dispatch = {"sentence": self._by_sentence, "word": self._by_word,
                        "paragraph": self._by_paragraph, "smart": self._by_smart}
            raw = [c for c in dispatch[self.strategy](text) if c.strip()]
            ts = datetime.now().isoformat(timespec="seconds")
            out = []
            for i, t in enumerate(raw, 1):
                issues = self._validate(t)
                out.append({"text": t, "position": i, "total_chunks": len(raw),
                            "source": source or self.source, "timestamp": ts,
                            "strategy": self.strategy, "word_count": len(t.split()),
                            "char_count": len(t), "issues": issues, "valid": not issues})
            return out

