# 4. EXERCISE 3: RAGPipeline (closes the loop: load -> retrieve -> generate)
# =====================================================================
def build_grounded_prompt(query: str, chunks: List[str]) -> str:
    """Numbered context blocks + the same grounding rule already used in the
    twin's core system prompt ('use only supplied data, say so if evidence is
    missing') -- kept consistent rather than writing a separate philosophy
    for this new capability."""
    context = "\n\n".join(f"[{i}] {c}" for i, c in enumerate(chunks, 1))
    return (
        "Answer the question using ONLY the context below. If the context is "
        "insufficient to answer confidently, say so explicitly rather than "
        "using outside knowledge.\n\n"
        f"CONTEXT:\n{context}\n\n"
        f"QUESTION:\n{query}\n\n"
        "ANSWER:"
    )


NO_GENERATOR_MESSAGE = (
    "[no generate_fn attached -- this is not a model response] "
    "Retrieved context is shown above; pass generate_fn to RAGPipeline to have "
    "it answered by the digital twin's model."
)
NO_CONTEXT_MESSAGE = "No relevant context was found in the index for this query; cannot answer using only supplied data."


class RAGPipeline:
    """
    Wires load_and_preprocess() -> SimpleRAGRetriever -> generation into two
    methods, because indexing and querying happen at different times and
    different frequencies and shouldn't be conflated into one run() call
    (unlike DigitalTwinPipeline/EmbeddingPipeline's single-shot run()).

    Two separate history logs (index_log, query_log) rather than one shared
    run_history, since indexing runs and query runs track different fields.
    """

    def __init__(self, chunk_strategy: str = "smart", max_chunk_size: int = 100,
                top_n: int = 3, generate_fn: Optional[Callable[[str], str]] = None):
        if chunk_strategy not in ChunkingSystem.STRATEGIES:
            raise ValueError(f"chunk_strategy must be one of {ChunkingSystem.STRATEGIES}, got '{chunk_strategy}'.")
        if max_chunk_size <= 0:
            raise ValueError(f"max_chunk_size must be positive, got {max_chunk_size}.")
        if top_n <= 0:
            raise ValueError(f"top_n must be positive, got {top_n}.")
        if generate_fn is not None and not callable(generate_fn):
            raise TypeError("generate_fn must be callable(prompt: str) -> str.")

        self.chunk_strategy, self.max_chunk_size, self.top_n = chunk_strategy, max_chunk_size, top_n
        self.generate_fn = generate_fn
        self.retriever = SimpleRAGRetriever()
        self.indexed_chunks: List[str] = []
        self.index_log: List[dict] = []
        self.query_log: List[dict] = []
        logger.info("RAGPipeline ready: chunk_strategy=%s max_chunk_size=%d top_n=%d generator=%s",
                    chunk_strategy, max_chunk_size, top_n, "attached" if generate_fn else "none (fallback)")

    # ---- phase 1: build the knowledge base --------------------------------
    def index(self, documents: List[Dict[str, str]]) -> dict:
        """Loads/preprocesses documents and adds every resulting chunk to the
        retriever. If a document produces zero chunks (chunking disabled, or
        text too short for the chunker to keep), its whole cleaned text is
        indexed instead, so it doesn't silently vanish from the index."""
        ts = datetime.now().isoformat(timespec="seconds")
        try:
            result = load_and_preprocess(documents, chunk_strategy=self.chunk_strategy,
                                         max_chunk_size=self.max_chunk_size)
        except (ValueError, TypeError) as e:
            entry = {"timestamp": ts, "ok": False, "error": str(e), "chunks_added": 0,
                     "documents_processed": 0, "documents_skipped": 0}
            self.index_log.append(entry)
            logger.error("index() failed: %s", e)
            return entry

        new_chunks = []
        for doc in result["documents"]:
            texts = [c["text"] for c in doc["chunks"]] or [doc["text"]]
            new_chunks.extend(texts)

        self.indexed_chunks.extend(new_chunks)
        try:
            self.retriever.add_documents(self.indexed_chunks)
            ok = True
        except ValueError as e:
            ok = False
            logger.error("retriever.add_documents failed after index(): %s", e)

        entry = {"timestamp": ts, "ok": ok, "error": None if ok else "no indexable text produced",
                 "chunks_added": len(new_chunks), "total_chunks": len(self.indexed_chunks),
                 "documents_processed": result["processed_count"], "documents_skipped": result["skipped_count"],
                 "skipped_detail": result["skipped"]}
        self.index_log.append(entry)
        if result["skipped_count"]:
            logger.warning("index(): %d document(s) skipped: %s", result["skipped_count"], result["skipped"])
        logger.info("index(): +%d chunks (total %d) from %d/%d documents.",
                    len(new_chunks), len(self.indexed_chunks), result["processed_count"], result["total_input"])
        return entry

    # ---- phase 2: answer a query -------------------------------------------
    def ask(self, query, top_n: Optional[int] = None) -> dict:
        """Never raises. Every failure mode -- bad query, empty index,
        retrieval error, generation error -- is recorded in the returned
        dict instead, and retrieval results are preserved even if generation
        afterwards fails (per-stage isolation)."""
        ts = datetime.now().isoformat(timespec="seconds")
        n = top_n or self.top_n
        result = {"timestamp": ts, "query": query, "retrieved": [], "answer": None,
                  "error": None, "warnings": []}

        if query is None or not isinstance(query, str) or query.strip() == "":
            result["error"] = ("query cannot be None" if query is None
                               else f"query must be a str, got {type(query).__name__}" if not isinstance(query, str)
                               else "query cannot be an empty string")
            logger.error("ask() rejected: %s", result["error"])
            self.query_log.append(result)
            return result

        if not self.indexed_chunks:
            result["error"] = "Index is empty. Call index() with at least one document first."
            logger.error("ask(): %s", result["error"])
            self.query_log.append(result)
            return result

        try:
            raw = self.retriever.process(query, top_n=n)
        except Exception as e:                                    # retriever's own contract can still surprise us
            result["error"] = f"retrieval failed: {e}"
            logger.error("ask(): retrieval failed: %s", e)
            self.query_log.append(result)
            return result

        retrieved = [(doc, score) for doc, score in raw if doc is not None]
        result["retrieved"] = [{"text": d, "score": round(s, 4)} for d, s in retrieved]

        if not retrieved:
            result["warnings"].append("no chunks matched this query")
            result["answer"] = NO_CONTEXT_MESSAGE
            logger.warning("ask(): no matching chunks for query %r; skipping generation.", query)
            self.query_log.append(result)
            return result

        prompt = build_grounded_prompt(query, [d for d, _ in retrieved])
        result["prompt"] = prompt
        if self.generate_fn is None:
            result["answer"] = NO_GENERATOR_MESSAGE
        else:
            try:
                result["answer"] = self.generate_fn(prompt)
            except Exception as e:
                result["error"] = f"generation failed: {e}"
                result["answer"] = None
                logger.error("ask(): generation failed: %s", e)

        self.query_log.append(result)
        return result

    # ---- visualization ---------------------------------------------------
    def visualize(self, title: Optional[str] = None):
        """Left: chunks indexed per index() run (red bar = that run had an
        error). Right: retrieval scores for the most recent ask() call,
        capped at [0, 1] since bag-of-words cosine similarity over
        non-negative counts is bounded there."""
        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12.5, 4.8))

        if self.index_log:
            xs = list(range(1, len(self.index_log) + 1))
            heights = [e["chunks_added"] for e in self.index_log]
            colors = ["firebrick" if not e["ok"] else "steelblue" for e in self.index_log]
            ax1.bar(xs, heights, color=colors)
            ax1.set_xticks(xs)
        ax1.set_title("Chunks added per index() run")
        ax1.set_xlabel("index() call #  (red = error)")
        ax1.set_ylabel("chunks added")

        last = self.query_log[-1] if self.query_log else None
        if last and last["retrieved"]:
            items = sorted(last["retrieved"], key=lambda r: r["score"])
            labels = [r["text"][:40] + ("..." if len(r["text"]) > 40 else "") for r in items]
            scores = [r["score"] for r in items]
            ax2.barh(labels, scores, color="seagreen")
            ax2.set_xlim(0, 1)
            ax2.set_title(f"Retrieval scores -- most recent query\n{last['query'][:50]!r}")
            ax2.set_xlabel("cosine similarity")
        else:
            ax2.text(0.5, 0.5, "No chunks retrieved" if last else "No query asked yet",
                     ha="center", va="center", transform=ax2.transAxes, fontsize=11, color="gray")
            ax2.set_xticks([]); ax2.set_yticks([])
            ax2.set_title("Retrieval scores -- most recent query")

        fig.suptitle(title or "RAG pipeline status")
        plt.tight_layout()
        plt.show()

    def summary(self) -> str:
        lines = [f"RAGPipeline  |  indexed chunks: {len(self.indexed_chunks)}  "
                f"generator: {'attached' if self.generate_fn else 'none (fallback)'}",
                f"index() runs: {len(self.index_log)}  ask() calls: {len(self.query_log)}"]
        if self.query_log:
            last = self.query_log[-1]
            lines.append(f"last query: {last['query']!r}")
            if last["error"]:
                lines.append(f"  -> error: {last['error']}")
            else:
                lines.append(f"  -> {len(last['retrieved'])} chunk(s) retrieved, "
                            f"answer: {str(last['answer'])[:80]}")
        return "\n".join(lines)


