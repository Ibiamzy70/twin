def benchmark(n_docs: int = 2000, repeats: int = 10) -> dict:
    """Times the vectorized process() (one matrix-vector product against the
    whole knowledge base) against a naive per-document Python loop, at a
    knowledge-base size where the difference is real. Median of several
    repeats, since a single call is noisy."""
    rng_words = ["python", "coding", "presentation", "sql", "docker", "research",
                "running", "morning", "coffee", "workflow", "reporting", "api"]
    import random
    rnd = random.Random(3)
    docs = [" ".join(rnd.choices(rng_words, k=8)) for _ in range(n_docs)]

    r = SimpleRAGRetriever()
    r.add_documents(docs)
    query = "python coding presentation"

    def naive(query, top_n):
        qtok = query.lower().split()
        qvec = r._vectorize(qtok)
        qnorm = np.linalg.norm(qvec)
        scores = []
        for doc, dvec in zip(r.data, r.doc_vectors):
            dnorm = np.linalg.norm(dvec)
            sim = 0.0 if dnorm == 0 else float(np.dot(qvec, dvec) / (qnorm * dnorm))
            scores.append((doc, sim))
        scores.sort(key=lambda x: x[1], reverse=True)
        return scores[:top_n]

    fast_times, naive_times = [], []
    for _ in range(repeats):
        t0 = time.perf_counter(); r.process(query, top_n=5); fast_times.append(time.perf_counter() - t0)
        t0 = time.perf_counter(); naive(query, 5); naive_times.append(time.perf_counter() - t0)

    fast_med, naive_med = statistics.median(fast_times), statistics.median(naive_times)
    return {"n_docs": n_docs, "repeats": repeats, "vectorized_median_s": round(fast_med, 5),
            "naive_loop_median_s": round(naive_med, 5),
            "speedup_x": round(naive_med / fast_med, 1) if fast_med else None}


