import numpy as np

class SimpleWordEmbeddings:
    """
    Basic demonstration of Word2Vec/GloVe internals:
    words represented as fixed-length numeric vectors, with
    similarity measured via cosine similarity.

    This does NOT train real embeddings (that requires a large
    corpus and a training algorithm like skip-gram or co-occurrence
    matrix factorization). It uses a small hardcoded vocabulary to
    demonstrate the *mechanics* — vector lookup, similarity, and
    nearest-neighbor search — that real embeddings rely on.
    """

    def __init__(self, dim: int = 4, seed: int = 42):
        self.dim = dim
        self.data = {}
        rng = np.random.default_rng(seed)

        # Small demo vocabulary relevant to the digital twin project.
        # In a real system these vectors would come from training,
        # not random initialization.
        vocab = ["running", "coding", "python", "presentation",
                 "coffee", "morning", "research", "workflow"]
        for word in vocab:
            self.data[word] = rng.normal(size=dim)

        # Hand-nudge a couple of vectors closer together so similarity
        # results are meaningful for testing, rather than pure noise.
        self.data["coding"] = self.data["python"] + rng.normal(scale=0.1, size=dim)

    def process(self, input_data):
        """
        Look up the embedding vector for a word.
        """
        if input_data is None:
            raise ValueError("input_data cannot be None")
        if not isinstance(input_data, str):
            raise TypeError(f"Expected str, got {type(input_data).__name__}")
        if input_data.strip() == "":
            raise ValueError("input_data cannot be an empty string")

        word = input_data.lower().strip()
        if word not in self.data:
            raise KeyError(f"'{word}' not in vocabulary. Known words: {list(self.data.keys())}")

        return self.data[word]

    def similarity(self, word1: str, word2: str) -> float:
        """Cosine similarity between two word vectors."""
        v1, v2 = self.process(word1), self.process(word2)
        return float(np.dot(v1, v2) / (np.linalg.norm(v1) * np.linalg.norm(v2)))


