import re

def extract_profile_data(text: str) -> dict:
    """Extract personal identifiers, temporal info, and preferences from text."""

    patterns = {
        'email':    r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b',
        'phone':    r'\+?\d{1,3}[-.]?\d{3}[-.]?\d{3}[-.]?\d{4}',
        'handle':   r'(?<![\w.])@\w+',   # not preceded by a word char, so emails are skipped
        'date':     r'\b\d{4}-\d{2}-\d{2}\b',
        'time':     r'\b\d{1,2}:\d{2}(?::\d{2})?\s?(?:am|pm)?',
        'duration': r'\b\d+\s?(?:hours?|hrs?|h|minutes?|mins?|m|seconds?|secs?|s)\b',
        'hashtag':  r'#\w+',
    }

    def find(name):
        return re.findall(patterns[name], text, re.IGNORECASE)

    return {
        "identifiers": {
            "emails": find('email'),
            "phones": find('phone'),
            "handles": find('handle'),
        },
        "temporal": {
            "dates": find('date'),
            "times": [t.strip() for t in find('time')],
            "durations": find('duration'),
        },
        "preferences": {
            "interests": [tag.lstrip('#').lower() for tag in find('hashtag')],
        },
    }

