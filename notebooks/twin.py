# ===========================================================================
class RateLimiter:
    """
    Sliding-window rate limiter: tracks timestamps of recent calls per
    identifier (e.g. a user id or session id) and rejects once the limit
    is exceeded within the window. Pure in-memory, single-process — a
    production multi-instance deployment would need a shared store
    (Redis, etc.) instead of per-process deques.
    """

    def __init__(self, max_calls: int = 10, window_seconds: float = 60.0):
        if max_calls <= 0:
            raise ValueError(f"max_calls must be positive, got {max_calls}.")
        if window_seconds <= 0:
            raise ValueError(f"window_seconds must be positive, got {window_seconds}.")
        self.max_calls = max_calls
        self.window_seconds = window_seconds
        self._calls: Dict[str, deque] = {}

    def check(self, identifier: str = "default") -> Dict[str, Any]:
        """Check whether a call is allowed for this identifier right now,
        WITHOUT consuming a slot. Use allow() to check-and-record."""
        now = time.monotonic()
        q = self._calls.setdefault(identifier, deque())
        while q and now - q[0] > self.window_seconds:
            q.popleft()
        remaining = self.max_calls - len(q)
        return {
            "allowed": remaining > 0,
            "remaining": max(0, remaining),
            "limit": self.max_calls,
            "window_seconds": self.window_seconds,
            "retry_after": round(self.window_seconds - (now - q[0]), 1) if (q and remaining <= 0) else 0,
        }

    def allow(self, identifier: str = "default") -> bool:
        """Checks the limit and, if allowed, records this call. Returns
        False without recording if the limit is already hit."""
        status = self.check(identifier)
        if not status["allowed"]:
            return False
        self._calls.setdefault(identifier, deque()).append(time.monotonic())
        return True

    def reset(self, identifier: Optional[str] = None):
        """Clear rate-limit history for one identifier, or all if None."""
        if identifier is None:
            self._calls.clear()
        else:
            self._calls.pop(identifier, None)


