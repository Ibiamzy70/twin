class ViolationLog:
    """Structured, queryable record of every safety violation, separate from
    the plain-text logger lines (so a dashboard/report could read this back
    without parsing log text)."""

    def __init__(self):
        self.entries: List[Dict[str, Any]] = []

    def record(self, source: str, identifier: str, violation_type: str,
               details: Dict[str, Any], text_snippet: str):
        entry = {
            "timestamp": datetime.now().isoformat(timespec="seconds"),
            "source": source,              # "input" or "output"
            "identifier": identifier,      # user/session id
            "violation_type": violation_type,
            "details": details,
            "text_snippet": text_snippet[:80] + ("..." if len(text_snippet) > 80 else ""),
        }
        self.entries.append(entry)
        safety_logger.warning("[%s] %s violation for '%s': %s | snippet: %r",
                               source, violation_type, identifier, details, entry["text_snippet"])
        return entry

    def report(self, identifier: Optional[str] = None) -> Dict[str, Any]:
        rows = [e for e in self.entries if identifier is None or e["identifier"] == identifier]
        by_type: Dict[str, int] = {}
        for e in rows:
            by_type[e["violation_type"]] = by_type.get(e["violation_type"], 0) + 1
        return {"total_violations": len(rows), "by_type": by_type, "entries": rows}


