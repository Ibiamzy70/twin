import numpy as np
from typing import List, Dict, Any
from collections import defaultdict

def build_embeddings(documents: List[str],
                      dim: int = 4,
                      window: int = 2,
                      min_count: int = 1,
                      **kwargs) -> Dict[str, Any]:
    """
    Build simple word embeddings from scratch using a co-occurrence
    matrix, reduced to `dim` dimensions via SVD (the same core idea
    GloVe uses: factorize a co-occurrence matrix into dense vectors).

    Args:
        documents: List of text documents to learn embeddings from
        dim: Target embedding dimension
        window: Context window size (how many neighboring words count
                as "co-occurring" with a given word)
        min_count: Minimum word frequency to be included in the vocabulary
        **kwargs: Reserved for future options

    Returns:
        dict: vocabulary, vectors, co-occurrence matrix, and metadata
    """
    # --- Parameter validation ---
    if documents is None:
        raise ValueError("documents cannot be None. Pass a list of strings.")
    if not isinstance(documents, list):
        raise TypeError(f"documents must be a list, got {type(documents).__name__}.")
    if len(documents) == 0:
        raise ValueError("documents is empty. Provide at least one document.")
    if not all(isinstance(d, str) for d in documents):
        bad = [i for i, d in enumerate(documents) if not isinstance(d, str)]
        raise TypeError(f"All documents must be strings. Non-string items at indices: {bad}")
    if dim <= 0:
        raise ValueError(f"dim must be a positive integer, got {dim}.")
    if window <= 0:
        raise ValueError(f"window must be a positive integer, got {window}.")
    if min_count <= 0:
        raise ValueError(f"min_count must be a positive integer, got {min_count}.")

    # --- Build vocabulary ---
    tokenized = [doc.lower().split() for doc in documents]
    word_counts = defaultdict(int)
    for tokens in tokenized:
        for word in tokens:
            word_counts[word] += 1

    vocab = sorted([w for w, c in word_counts.items() if c >= min_count])
    if len(vocab) < 2:
        raise ValueError(
            f"Vocabulary too small ({len(vocab)} words after min_count={min_count} filter). "
            "Provide more text or lower min_count."
        )
    word_to_idx = {w: i for i, w in enumerate(vocab)}
    vocab_size = len(vocab)

    if dim >= vocab_size:
        raise ValueError(
            f"dim ({dim}) must be smaller than vocabulary size ({vocab_size}). "
            "Reduce dim or provide more text."
        )

    # --- Build co-occurrence matrix ---
    cooc = np.zeros((vocab_size, vocab_size))
    for tokens in tokenized:
        for i, word in enumerate(tokens):
            if word not in word_to_idx:
                continue
            word_idx = word_to_idx[word]
            start = max(0, i - window)
            end = min(len(tokens), i + window + 1)
            for j in range(start, end):
                if j == i or tokens[j] not in word_to_idx:
                    continue
                cooc[word_idx][word_to_idx[tokens[j]]] += 1

    # --- Factorize into dense vectors via SVD ---
    U, S, _ = np.linalg.svd(cooc)
    vectors = U[:, :dim] * S[:dim]

    embeddings = {word: vectors[idx] for word, idx in word_to_idx.items()}

    return {
        "vocab_size": vocab_size,
        "dim": dim,
        "window": window,
        "vocabulary": vocab,
        "embeddings": embeddings,
        "cooccurrence_matrix": cooc,
    }


def most_similar(embeddings: Dict[str, np.ndarray], word: str, top_n: int = 3) -> List[tuple]:
    """Find the top_n most similar words to `word` by cosine similarity."""
    if word not in embeddings:
        raise KeyError(f"'{word}' not in vocabulary. Known words: {list(embeddings.keys())}")

    target = embeddings[word]
    scores = []
    for other_word, vec in embeddings.items():
        if other_word == word:
            continue
        sim = float(np.dot(target, vec) / (np.linalg.norm(target) * np.linalg.norm(vec) + 1e-10))
        scores.append((other_word, sim))

    return sorted(scores, key=lambda x: x[1], reverse=True)[:top_n]


