class ChunkingSystem:
    STRATEGIES = ("sentence", "word", "paragraph", "smart")

    def __init__(self, strategy: str = "smart", source: str = "unknown",
                 sentences_per_chunk: int = 3,
                 words_per_chunk: int = 50, overlap: int = 10,
                 max_chunk_size: int = 50,
                 min_words: int = 8, max_words: int = 80):
        if strategy not in self.STRATEGIES:
            raise ValueError(f"Unknown strategy '{strategy}'. Choose from {self.STRATEGIES}")
        if overlap >= words_per_chunk:
            raise ValueError("overlap must be smaller than words_per_chunk")

        self.strategy = strategy
        self.source = source
        self.sentences_per_chunk = sentences_per_chunk
        self.words_per_chunk = words_per_chunk
        self.overlap = overlap
        self.max_chunk_size = max_chunk_size
        self.min_words = min_words
        self.max_words = max_words

    # ---------- Splitting helpers ----------
    @staticmethod
    def _paragraphs(text: str) -> List[str]:
        return [p.strip() for p in re.split(r'\n\s*\n', text.strip()) if p.strip()]

    @staticmethod
    def _sentences(text: str) -> List[str]:
        return [s for s in re.split(r'(?<=[.!?])\s+', text.strip()) if s]

    # ---------- Strategies ----------
    def _by_sentence(self, text: str) -> List[str]:
        sents = self._sentences(text)
        n = self.sentences_per_chunk
        return [" ".join(sents[i:i + n]) for i in range(0, len(sents), n)]

    def _by_word(self, text: str) -> List[str]:
        words = text.split()
        step = self.words_per_chunk - self.overlap
        chunks = []
        for i in range(0, len(words), step):
            chunks.append(" ".join(words[i:i + self.words_per_chunk]))
            if i + self.words_per_chunk >= len(words):
                break
        return chunks

    def _by_paragraph(self, text: str) -> List[str]:
        return [" ".join(p.split()) for p in self._paragraphs(text)]

    def _by_smart(self, text: str) -> List[str]:
        # Pack whole paragraphs up to max_chunk_size words.
        # Overlap = the last sentence of the previous chunk (keeps sentences intact).
        chunks, current = [], ""
        for para in self._paragraphs(text):
            para = " ".join(para.split())
            if current and len(current.split()) + len(para.split()) > self.max_chunk_size:
                chunks.append(current)
                current = self._sentences(current)[-1] + " " + para
            else:
                current = f"{current} {para}".strip()
        if current:
            chunks.append(current)
        return chunks

    # ---------- Validation ----------
    def _validate(self, text: str) -> List[str]:
        issues = []
        n_words = len(text.split())

        if n_words < self.min_words:
            issues.append(f"too small ({n_words} words)")
        if n_words > self.max_words:
            issues.append(f"too large ({n_words} words)")
        if not (text[0].isupper() or text[0].isdigit()):
            issues.append("starts mid-sentence")
        if text[-1] not in ".!?":
            issues.append("ends mid-sentence")
        return issues

    # ---------- Main entry point ----------
    def chunk(self, text: str, source: str = None) -> List[Dict[str, Any]]:
        dispatch = {
            "sentence": self._by_sentence,
            "word": self._by_word,
            "paragraph": self._by_paragraph,
            "smart": self._by_smart,
        }
        raw_chunks = [c for c in dispatch[self.strategy](text) if c.strip()]
        timestamp = datetime.now().isoformat(timespec="seconds")

        results = []
        for i, chunk_text in enumerate(raw_chunks, 1):
            issues = self._validate(chunk_text)
            results.append({
                "text": chunk_text,
                "position": i,
                "total_chunks": len(raw_chunks),
                "source": source or self.source,
                "timestamp": timestamp,
                "strategy": self.strategy,
                "word_count": len(chunk_text.split()),
                "char_count": len(chunk_text),
                "issues": issues,
                "valid": not issues,
            })
        return results

    def report(self, chunks: List[Dict[str, Any]]) -> None:
        print(f"Strategy: {self.strategy} | chunks: {len(chunks)}")
        if not chunks:
            return
        wc = [c["word_count"] for c in chunks]
        bad = [c for c in chunks if not c["valid"]]
        print(f"  words min/avg/max: {min(wc)}/{sum(wc) / len(wc):.1f}/{max(wc)}")
        print(f"  valid chunks: {len(chunks) - len(bad)}/{len(chunks)}")
        for c in bad:
            print(f"  ⚠️ chunk {c['position']}: {'; '.join(c['issues'])}")
        print()


