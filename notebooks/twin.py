class DigitalTwinPipeline:
    """
    Production pipeline that takes raw text (e.g. activity logs, notes,
    conversation transcripts) and prepares it for use as digital twin
    context: token-budget checked, chunked, and with structured data
    (emails, dates, hashtags, etc.) extracted.

    Parameters
    ----------
    context_window : int
        Max tokens the target model can accept in one call.
    chars_per_token : float
        Rough estimate for converting characters to tokens.
    chunk_strategy : str
        One of "sentence", "word", "paragraph", "smart" (see ChunkingSystem).
    max_chunk_size : int
        Passed to ChunkingSystem as the word-count ceiling per chunk.

    Example
    -------
    >>> pipeline = DigitalTwinPipeline(context_window=8192)
    >>> result = pipeline.run(long_document, source="activity_log.txt")
    >>> pipeline.visualize(result)
    """

    def __init__(self,
                 context_window: int = 8192,
                 chars_per_token: float = 4.0,
                 chunk_strategy: str = "smart",
                 max_chunk_size: int = 200,
                 min_words: int = 8,
                 max_words: int = 300):
        if context_window <= 0:
            raise ValueError(f"context_window must be positive, got {context_window}.")
        if chars_per_token <= 0:
            raise ValueError(f"chars_per_token must be positive, got {chars_per_token}.")

        self.context_window = context_window
        self.chars_per_token = chars_per_token
        self.chunker = ChunkingSystem(
            strategy=chunk_strategy,
            max_chunk_size=max_chunk_size,
            words_per_chunk=max_chunk_size,
            overlap=min(20, max_chunk_size - 1),
            min_words=min_words,
            max_words=max_words,
        )
        self.run_history: List[Dict[str, Any]] = []
        logger.info(f"Pipeline initialized: context_window={context_window}, "
                    f"strategy={chunk_strategy}, max_chunk_size={max_chunk_size}")

    # -----------------------------------------------------------------
    # Core pipeline
    # -----------------------------------------------------------------
    def run(self, text: str, source: str = "unknown") -> Dict[str, Any]:
        """
        Run the full pipeline on a piece of text.

        Returns a dict with: source, timestamp, token estimate, chunks,
        extracted structured data, and any warnings/errors encountered.
        """
        run_id = len(self.run_history) + 1
        timestamp = datetime.now().isoformat(timespec="seconds")
        logger.info(f"[run {run_id}] starting | source={source}")

        result = {
            "run_id": run_id,
            "source": source,
            "timestamp": timestamp,
            "token_estimate": None,
            "chunks": [],
            "extracted_data": {},
            "warnings": [],
            "errors": [],
        }

        # 1. Input validation
        try:
            self._validate_input(text)
        except (ValueError, TypeError) as e:
            logger.error(f"[run {run_id}] input validation failed: {e}")
            result["errors"].append(str(e))
            self.run_history.append(result)
            return result

        # 2. Token / context-window estimate
        try:
            result["token_estimate"] = self._estimate_tokens(text)
            if not result["token_estimate"]["fits"]:
                warning = (f"Text exceeds context window: "
                           f"{result['token_estimate']['estimated_tokens']} tokens "
                           f"> {self.context_window} limit")
                logger.warning(f"[run {run_id}] {warning}")
                result["warnings"].append(warning)
        except Exception as e:
            logger.error(f"[run {run_id}] token estimation failed: {e}")
            result["errors"].append(f"token estimation failed: {e}")

        # 3. Chunking
        try:
            chunks = self.chunker.chunk(text, source=source)
            result["chunks"] = chunks
            invalid = [c for c in chunks if not c["valid"]]
            if invalid:
                warning = f"{len(invalid)}/{len(chunks)} chunks flagged by validator"
                logger.warning(f"[run {run_id}] {warning}")
                result["warnings"].append(warning)
            logger.info(f"[run {run_id}] created {len(chunks)} chunks "
                        f"({len(chunks) - len(invalid)} valid)")
        except Exception as e:
            logger.error(f"[run {run_id}] chunking failed: {e}")
            result["errors"].append(f"chunking failed: {e}")

        # 4. Structured data extraction
        try:
            result["extracted_data"] = extract_profile_data(text)
            n_found = sum(len(v) for cat in result["extracted_data"].values() for v in cat.values())
            logger.info(f"[run {run_id}] extracted {n_found} structured data points")
        except Exception as e:
            logger.error(f"[run {run_id}] extraction failed: {e}")
            result["errors"].append(f"extraction failed: {e}")

        self.run_history.append(result)
        logger.info(f"[run {run_id}] complete | warnings={len(result['warnings'])} "
                    f"errors={len(result['errors'])}")
        return result

    # -----------------------------------------------------------------
    # Helpers
    # -----------------------------------------------------------------
    def _validate_input(self, text):
        if text is None:
            raise ValueError("text cannot be None")
        if not isinstance(text, str):
            raise TypeError(f"text must be a str, got {type(text).__name__}")
        if text.strip() == "":
            raise ValueError("text is empty or whitespace-only")

    def _estimate_tokens(self, text: str) -> Dict[str, Any]:
        char_count = len(text)
        estimated_tokens = round(char_count / self.chars_per_token)
        return {
            "char_count": char_count,
            "estimated_tokens": estimated_tokens,
            "fits": estimated_tokens <= self.context_window,
            "usage_percent": round((estimated_tokens / self.context_window) * 100, 2),
        }

    # -----------------------------------------------------------------
    # Visualization
    # -----------------------------------------------------------------
    def visualize(self, result: Dict[str, Any]) -> None:
        """
        Plot chunk word-count distribution and token-budget usage
        for a single run() result.
        """
        chunks = result.get("chunks", [])
        if not chunks:
            logger.warning("No chunks to visualize for this run.")
            return

        fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(12, 5))

        # Left: chunk sizes, colored by validity
        positions = [c["position"] for c in chunks]
        counts = [c["word_count"] for c in chunks]
        colors = ["seagreen" if c["valid"] else "indianred" for c in chunks]
        ax1.bar(positions, counts, color=colors)
        ax1.set_title(f"Chunk sizes ({result['source']})")
        ax1.set_xlabel("Chunk position")
        ax1.set_ylabel("Word count")
        ax1.set_xticks(positions)

        # Right: token budget usage as a simple gauge bar
        usage = result["token_estimate"]["usage_percent"] if result["token_estimate"] else 0
        bar_color = "seagreen" if usage <= 100 else "indianred"
        ax2.barh(["Context window usage"], [min(usage, 150)], color=bar_color)
        ax2.axvline(100, color="black", linestyle="--", label="100% limit")
        ax2.set_xlim(0, 150)
        ax2.set_xlabel("% of context window used")
        ax2.set_title(f"Token budget: {usage}%")
        ax2.legend()

        fig.suptitle(f"Run {result['run_id']} | {result['timestamp']}")
        plt.tight_layout()
        plt.show()

    # -----------------------------------------------------------------
    # Summary / debugging
    # -----------------------------------------------------------------
    def summary(self) -> None:
        """Print a summary of every run so far — useful for debugging."""
        if not self.run_history:
            print("No runs yet.")
            return
        for r in self.run_history:
            print(f"Run {r['run_id']} | {r['source']} | {r['timestamp']}")
            print(f"  tokens: {r['token_estimate']}")
            print(f"  chunks: {len(r['chunks'])} | warnings: {len(r['warnings'])} "
                  f"| errors: {len(r['errors'])}")
            if r["errors"]:
                print(f"  ⚠️ errors: {r['errors']}")


