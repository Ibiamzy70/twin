# 3. TOKEN ESTIMATION
#    Same raise/zero-result rules as Exercise 1 & 2. Adds a second, word-based
#    estimate so callers get a [low, high] range instead of one bare number --
#    a reminder, every call, that this is an approximation, not a real count.
